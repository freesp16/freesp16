#!/usr/bin/env python3
"""The output routing smoke check on the Linux desktop (run by scripts/host-smoke.sh CHECK=routing). Two subcommands:

  tools/routing-check.py script --out FILE --input-wav IN.wav
      writes one scripted-input session (ScriptedInput format, io/controllers/ScriptedInput.h) and the LINE IN stand-in
      (a 1 kHz sine at -12 dBFS, stereo, 3 s = whole cycles, looped by the file device). The app runs with the file
      device writing every logical port (audio_file_ports=all: MAIN 0/1, OUT3-4 2/3, OUT5-6 4/5, OUT7-8 6/7, PHONES
      8/9, FILTER SEND 10/11) and audio_input=file:IN.wav; track 1 plays the 440 Hz test tone (-12 dBFS). Phases:
        A  defaults: M + 6CH, every OUT ASSIGN "--", HP CUE MASTER
        B  `cmd param routing.outAssign 0 2`     track 1 -> OUT3-4 (stays in the master)
        C  `cmd param track.mode 1 2`            track 2 -> THRU: the LINE IN through the strip into the master
        D  `cmd param routing.assignMode 0 1`    8CH: MAIN carries only the "--" tracks (track 2), never the master
        E  `cmd param routing.headphoneCue 0 2`  HP CUE OUT3-4
  tools/routing-check.py verify --log LOG --wav WAV
      one line per check, exit 1 when one fails: the log (AUDIO ok file: ... x12, PARAM ... posted x4, xruns=0) and
      per phase (a window in its middle, +/- 0.8 s of slack for the script clock vs the WAV's first frame) the 440 Hz
      and 1 kHz levels (Goertzel) on MAIN, OUT3-4, OUT5-6/7-8, PHONES:
        A  MAIN 440; OUT3-4 silent; PHONES 440 (MASTER x HEADPHONES 100 = -6 dB)
        B  MAIN 440; OUT3-4 440; OUT5-6 / OUT7-8 silent
        C  MAIN 440 + 1 kHz; OUT3-4 440 without 1 kHz
        D  MAIN 1 kHz without 440; OUT3-4 440 without 1 kHz; PHONES 1 kHz (MASTER is not an 8CH cue: OUT1-2)
        E  PHONES 440 without 1 kHz
Standard library only."""
import argparse
import math
import re
import struct
import sys
import wave

TAG = re.compile(r"\[sp16-mod\] \S+ (.*)$")
T_B, T_C, T_D, T_E, T_QUIT = 2000, 4500, 7000, 9500, 12000
PHASES = {"A": (0.5, 1.3), "B": (2.8, 3.7), "C": (5.3, 6.2), "D": (7.8, 8.7), "E": (10.3, 11.2)}
PRESENT_DB, ABSENT_DB = -30.0, -60.0
CH = {"MAIN": (0, 1), "OUT3-4": (2, 3), "OUT5-6": (4, 5), "OUT7-8": (6, 7), "PHONES": (8, 9), "FILTER SEND": (10, 11)}


def script_cmd(a) -> int:
    lines = [
        "# generated by tools/routing-check.py (time 0 = the app's first frame)",
        f"{T_B} cmd param routing.outAssign 0 2",
        f"{T_C} cmd param track.mode 1 2",
        f"{T_D} cmd param routing.assignMode 0 1",
        f"{T_E} cmd param routing.headphoneCue 0 2",
        f"{T_QUIT} quit",
    ]
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    rate, frames = 44100, 3 * 44100
    with wave.open(a.input_wav, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(rate)
        data = bytearray()
        for n in range(frames):
            v = int(round(0.25 * 32767 * math.sin(2 * math.pi * 1000.0 * n / rate)))
            data += struct.pack("<hh", v, v)
        w.writeframes(bytes(data))
    return 0


def goertzel_db(x, rate, hz):
    if not x:
        return -200.0
    k = 2 * math.cos(2 * math.pi * hz / rate)
    s1 = s2 = 0.0
    for v in x:
        s1, s2 = v + k * s1 - s2, s1
    p = s1 * s1 + s2 * s2 - k * s1 * s2
    amp = 2 * math.sqrt(max(p, 0.0)) / len(x)
    return 20 * math.log10(amp) if amp > 0 else -200.0


def verify_cmd(a) -> int:
    fails = 0

    def check(ok, text):
        nonlocal fails
        print(("ok   " if ok else "FAIL ") + text)
        fails += 0 if ok else 1

    log = [m.group(1) for m in (TAG.search(l) for l in open(a.log, errors="replace")) if m]
    check(any(l.startswith("AUDIO ok file:") and " x12 " in l for l in log), "AUDIO ok file device with 12 channels")
    posted = [l for l in log if l.startswith("PARAM ") and l.endswith(" posted")]
    check(len(posted) == 4, f"PARAM lines posted: {len(posted)} of 4")
    last = [l for l in log if l.startswith("AUDIO alsa_periods=")]
    check(bool(last) and " xruns=0 " in last[-1], "AUDIO xruns=0")

    with wave.open(a.wav, "rb") as w:
        nch, rate, total = w.getnchannels(), w.getframerate(), w.getnframes()
        raw = w.readframes(total)
    check(nch == 12, f"WAV channels {nch} (12 = every logical port)")
    if nch != 12:
        return 1
    samples = struct.unpack(f"<{total * nch}h", raw)

    def level(port, start, end, hz):
        a0, b0 = int(start * rate), min(int(end * rate), total)
        best = -200.0
        for c in CH[port]:
            x = [samples[n * nch + c] / 32768.0 for n in range(a0, b0)]
            best = max(best, goertzel_db(x, rate, hz))
        return best

    def peak(port, start, end):
        a0, b0 = int(start * rate), min(int(end * rate), total)
        return max((abs(samples[n * nch + c]) for c in CH[port] for n in range(a0, b0)), default=0)

    def has(phase, port, hz):
        s, e = PHASES[phase]
        d = level(port, s, e, hz)
        check(d > PRESENT_DB, f"{phase}: {port} {hz} Hz present ({d:.1f} dBFS)")
        return d

    def lacks(phase, port, hz):
        s, e = PHASES[phase]
        d = level(port, s, e, hz)
        check(d < ABSENT_DB, f"{phase}: {port} no {hz} Hz ({d:.1f} dBFS)")

    def silent(phase, port):
        s, e = PHASES[phase]
        p = peak(port, s, e)
        check(p == 0, f"{phase}: {port} silent (peak {p})")

    check(total / rate > PHASES["E"][1], f"WAV length {total / rate:.2f} s")
    main_a = has("A", "MAIN", 440)
    silent("A", "OUT3-4")
    phones_a = has("A", "PHONES", 440)
    check(abs((main_a - phones_a) - 6.02) < 0.5, f"A: PHONES = MAIN - 6 dB ({main_a - phones_a:.2f} dB)")
    has("B", "MAIN", 440)
    has("B", "OUT3-4", 440)
    silent("B", "OUT5-6")
    silent("B", "OUT7-8")
    silent("B", "FILTER SEND")
    has("C", "MAIN", 440)
    has("C", "MAIN", 1000)
    has("C", "OUT3-4", 440)
    lacks("C", "OUT3-4", 1000)
    has("D", "MAIN", 1000)
    lacks("D", "MAIN", 440)
    has("D", "OUT3-4", 440)
    lacks("D", "OUT3-4", 1000)
    has("D", "PHONES", 1000)
    has("E", "PHONES", 440)
    lacks("E", "PHONES", 1000)
    print(f"routing-check: {'PASS' if fails == 0 else f'{fails} check(s) failed'}")
    return 0 if fails == 0 else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--out", required=True)
    s.add_argument("--input-wav", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--log", required=True)
    v.add_argument("--wav", required=True)
    a = ap.parse_args()
    return script_cmd(a) if a.cmd == "script" else verify_cmd(a)


if __name__ == "__main__":
    sys.exit(main())
