#!/usr/bin/env python3
"""The ratchet smoke check on the Linux desktop (run by scripts/host-smoke.sh CHECK=perf). Two subcommands:

  tools/perf-check.py script --out FILE --out-dir DIR
      writes one scripted-input session (ScriptedInput format, io/controllers/ScriptedInput.h), with the generated kit
      on scene 1: pad 1 selects track 1; the step keys enter FULL steps 1, 5, 9, 13 in pattern 1; `cmd lock` gives
      each a short HOLD (env.hold 20 = 4 ms, release 0: every hit is a burst followed by silence, so each repeat is a
      separate onset) and RETRIGGER locks — step 1: CNT 3 at 1/3 step, step 5: none (a single hit), step 9: CNT 4 at
      1/2 step, step 13: CNT 16 at 1 step (its 4th repeat meets the next pass's step 1 and is cancelled, the rest of
      the 15 never fire); `cmd state`; `cmd render DIR/perf.wav 6` (offline, the app's engine and pattern objects);
      quit.

  tools/perf-check.py verify --log LOG --render WAV
      one line per check, exit 1 when one fails:
        - M2 PATTERN scene=1 pattern=1: cells F1.1L,F5.1L,F9.1L,F13.1L
        - onsets on MAIN of the render's first pass (scene 1; the render then queues the empty scenes 2-4, and a scene
          switch ends pending ratchets) with tools/m2-check.py's detector (2 ms windows, -50 dBFS gate): one per step and
          one per ratchet repeat — repeat k of a step at frame t0 at t0 + round(k * step / divisor) (step = 15 * rate
          / BPM), the repeats at or after the track's next step cancelled — within 3 ms, none missing, none extra,
          and the same detector lag on every onset (the spacing is sample-exact)
        - live engine: xruns 0
      Not covered here (unit tests only): transpose and step shift (no `cmd` reaches them; their engine and model
      paths are tests/unit/sequencer/perf/).
Standard library only."""
import argparse
import importlib.util
import pathlib
import sys

_spec = importlib.util.spec_from_file_location("m2check", pathlib.Path(__file__).with_name("m2-check.py"))
m2 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(m2)

# step (1-based) -> (count, speed index): speed 0-5 = 1/8, 1/6, 1/4, 1/3, 1/2, 1 step
STEPS = {1: (3, 3), 5: (1, None), 9: (4, 4), 13: (16, 5)}
DIVISOR = [8, 6, 4, 3, 2, 1]


def script_cmd(a) -> int:
    ev = []
    t = 3000

    def at(ms, line):
        ev.append((ms, line))

    def key(name, gap=90):
        nonlocal t
        at(t, f"press {name}")
        at(t + 40, f"release {name}")
        t += gap

    def cmd(text, gap=150):
        nonlocal t
        at(t, f"cmd {text}")
        t += gap

    cmd("trigger-type full")
    key("pattern")
    key("step1")
    t += 400  # stopped: the switch is immediate
    key("pattern", 200)
    key("pad1", 300)  # selects track 1 (and plays it)
    for s in STEPS:
        key(f"step{s}")
    t += 200
    for s, (count, speed) in STEPS.items():
        cmd(f"lock {s} env.hold 20")
        cmd(f"lock {s} env.release 0")
        if count > 1:
            cmd(f"lock {s} seq.retrigCount {count}")
            cmd(f"lock {s} seq.retrigSpeed {speed}")
    cmd("state", 300)
    cmd(f"render {a.out_dir}/perf.wav 6", 1000)
    at(t, "quit")  # runs after the render (the UI thread renders synchronously)
    with open(a.out, "w") as f:
        f.write("# generated by tools/perf-check.py script (time 0 = the app's first frame)\n")
        for ms, line in sorted(ev, key=lambda e: e[0]):
            f.write(f"{ms} {line}\n")
    return 0


def expected(rate, bpm, total):
    """Onset frames of the steps and their repeats, from PPQ 0 at frame 0 (frameAt as tools/edit-check.py), up to
    `total` (the render's first scene switch: the other scenes are empty, and a switch ends the ratchets)."""
    ppf = bpm / (60.0 * rate)
    frame = lambda q: int(q / ppf + 1e-6)
    step2 = round(2 * 15.0 * rate / bpm)  # 2 x the step in frames (whole at 120 BPM / 44.1 or 48 kHz)
    hits = []  # (frame, step)
    q = 0.0
    while frame(q) < total:
        for s in STEPS:
            hits.append((frame(q + (s - 1) * 0.25), s))
        q += 16 * 0.25
    hits.sort()
    onsets = []
    for i, (t0, s) in enumerate(hits):
        if t0 >= total:
            break
        onsets.append(t0)
        count, speed = STEPS[s]
        nxt = hits[i + 1][0] if i + 1 < len(hits) else 1 << 62
        for k in range(1, count):
            d = DIVISOR[speed]
            r = t0 + (k * step2 + d) // (2 * d)  # round half up of k * step / d
            if r >= nxt or r >= total:
                break
            onsets.append(r)
    return onsets


def verify_cmd(a) -> int:
    ok = True

    def check(cond, text):
        nonlocal ok
        ok = ok and bool(cond)
        print(("PASS " if cond else "FAIL ") + text)

    log = m2.lines(a.log)
    _, pats = m2.state_after(log, None)
    by = {}
    for l in pats:
        d = m2.kv(l)
        by[(int(d["scene"]), int(d["pattern"]))] = d.get("cells", "")
    want = ",".join(f"F{s}.1L" for s in STEPS)
    check(by.get((1, 1)) == want, f"pattern 1 cells {by.get((1, 1))}, expected {want} (step keys + cmd lock)")
    r = [m2.kv(l) for l in log if l.startswith("RENDER file=")]
    check(r, "rendered")
    if not r:
        print("perf check: FAILED")
        return 1
    rate, total, bpm = float(r[-1]["rate"]), int(r[-1]["frames"]), float(r[-1]["tempo"])
    # The render queues scenes 2, 3, 4 at the pass ends (tools/m2-check.py's renders): scene 1 plays the first pass.
    switches = [int(m2.kv(l)["frame"]) for l in log if l.startswith("RENDER switch ")]
    # From the block of the switch on, scene 2's track 1 has no sample and the engine's temporary test tone sounds
    # (EngineOptions::testTone): the analysis stops at that block's start.
    end = min(switches + [total])
    end -= end % 64
    exp = expected(rate, bpm, end)
    rr, main = m2.read_main(a.render)
    got = [g for g in m2.detect_onsets(main[:end], rr) if g < end]
    tol = int(0.003 * rr)
    missing = [e for e in exp if not any(abs(g - e) <= tol for g in got)]
    extra = [g for g in got if not any(abs(g - e) <= tol for e in exp)]
    check(not missing and not extra and len(exp) == 4 + 2 + 3 + 3,
          f"onsets on MAIN: {len(got)} found, {len(exp)} expected (4 steps + 8 ratchet repeats), missing {missing[:4]}, "
          f"extra {extra[:4]}")
    # Every hit restarts the same sample at the same level, so the detector's lag behind the true start is the same
    # for all: equal lags = every repeat at its exact frame relative to its step.
    lags = sorted({min(got, key=lambda g: abs(g - e)) - e for e in exp}) if got else []
    check(len(lags) == 1, f"detector lag behind the expected frames {lags} (one value: sample-exact spacing)")
    loads = [m2.kv(l) for l in log if l.startswith("LOAD ")]
    check(loads and int(loads[-1]["xruns"]) == 0, f"live engine: xruns {loads[-1]['xruns'] if loads else '?'}")
    print("perf check:", "OK" if ok else "FAILED")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--out", required=True)
    s.add_argument("--out-dir", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--log", required=True)
    v.add_argument("--render", required=True)
    a = ap.parse_args()
    return script_cmd(a) if a.cmd == "script" else verify_cmd(a)


if __name__ == "__main__":
    sys.exit(main())
