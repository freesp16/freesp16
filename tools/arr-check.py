#!/usr/bin/env python3
"""The song mode smoke check on the Linux desktop (run by scripts/host-smoke.sh CHECK=arr). Two subcommands:

  tools/arr-check.py script --out FILE --out-dir DIR
      writes one scripted-input session (ScriptedInput format, io/controllers/ScriptedInput.h), transport stopped:
      `cmd pattern-length` gives patterns 1.2 / 2.2 8 steps and 2.1 64 steps (1.1 / 1.3 keep 16); the five rows are built
      with the row commands (append, insert before, COPY + PASTE, edit), then duplicate / move / delete and a coalesced
      BPM knob turn are each undone with one `cmd undo`; `cmd arr-state`, `cmd arr-play 1`, `cmd render DIR/arr.wav 21
      song` (offline: the arrangement in song mode, stop at the end), `cmd arr-state`; quit. Every action is ordered by
      the UI thread (commands execute in order, the render is synchronous), so the gaps only space the log.

  tools/arr-check.py verify --log LOG
      one line per check, exit 1 when one fails:
        - every ARR command line says ok; ARR STATE rows=5 with the expected rows and start table (sixteenths), before
          and after the render, play=1 after `arr-play 1`
        - RENDER song rows=5; the RENDER switch frames = the row starts modelled block by block (64-frame blocks, the
          boundary contract's frame rule ⌊(B − p0) / ppf + 1e-6⌋, a fixed BPM from the block after its row's start,
          "--" keeps the tempo), then the cue back to row 1 one block after the end
        - RENDER song row lines: each row's song position (SPP) = its start-table entry, logged in the block that
          contains its first sample; RENDER song end in the block that contains the end boundary (the transport stops
          from the next block)
        - the live engine: xruns 0
Standard library only."""
import argparse
import importlib.util
import pathlib
import sys

_spec = importlib.util.spec_from_file_location("m2check", pathlib.Path(__file__).with_name("m2-check.py"))
m2 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(m2)

# (scene, pattern, length in steps, repeats, bpm or 0 = "--"), 1-based scene / pattern.
SONG = [(1, 1, 16, 2, 0), (1, 2, 8, 3, 140), (2, 1, 64, 1, 0), (1, 3, 16, 1, 90), (2, 2, 8, 2, 0)]
LIST = "1.1x2@--,1.2x3@140.0,2.1x1@--,1.3x1@90.0,2.2x2@--"
COMMANDS = [
    "pattern-length 1 2 8", "pattern-length 2 1 64", "pattern-length 2 2 8",
    "arr-append 1 1 2 0",          # 1.1 x2
    "arr-append 2 1 1 0",          # 1.1, 2.1
    "arr-insert 2 1 2 3 140",      # 1.1, 1.2@140 x3, 2.1
    "arr-append 2 2 2 0",          # … 2.2 x2
    "arr-copy 2", "arr-paste 4",   # 1.1, 1.2, 2.1, 1.2 (pasted before row 4), 2.2
    "arr-edit 4 1 3 1 90",         # row 4 = 1.3 x1 @90 → the song
    "arr-dup 5", "undo",           # one step each
    "arr-move 1 5", "undo",
    "arr-delete 3", "undo",
    "arr-field 2 bpm 141", "arr-field 2 bpm 142", "undo",  # a knob turn: one step
    "arr-state",
    "arr-play 1",
]


def script_cmd(a) -> int:
    ev = []
    t = 3000
    for c in COMMANDS:
        ev.append((t, f"cmd {c}"))
        t += 120
    ev.append((t, f"cmd render {a.out_dir}/arr.wav 21 song"))
    t += 500
    ev.append((t, "cmd arr-state"))
    ev.append((t + 500, "quit"))  # runs after the render (the UI thread renders synchronously)
    with open(a.out, "w") as f:
        f.write("# generated by tools/arr-check.py script (time 0 = the app's first frame)\n")
        for ms, line in ev:
            f.write(f"{ms} {line}\n")
    return 0


def expected(rate, tempo0):
    """Row start frames (row index 1…4), the end frame and the start table, from PPQ 0 at frame 0."""
    starts, q = [], 0.0
    table, at = [0], 0
    for (_, _, length, repeats, _) in SONG:
        starts.append(q)
        q += repeats * length * 0.25
        at += repeats * length
        table.append(at)
    starts.append(q)
    tempo = SONG[0][4] or tempo0
    anchor, anchor_block = 0.0, 0
    rows, end, nxt, block = [], None, 1, 0
    while nxt <= len(SONG):
        ppf = tempo / (60.0 * rate)
        p0 = anchor + (block - anchor_block) * 64 * ppf
        p1 = anchor + (block + 1 - anchor_block) * 64 * ppf
        pending = 0
        while nxt <= len(SONG):
            f = (starts[nxt] - p0) / ppf + 1e-6
            if f >= 64:
                break
            frame = block * 64 + max(0, int(f))
            if nxt == len(SONG):
                end = frame
            else:
                rows.append((frame, nxt))
                pending = SONG[nxt][4] or pending
            nxt += 1
        if pending:
            anchor, anchor_block, tempo = p1, block + 1, pending
        block += 1
    return rows, end, table


def verify_cmd(a) -> int:
    ok = True

    def check(cond, text):
        nonlocal ok
        ok = ok and bool(cond)
        print(("PASS " if cond else "FAIL ") + text)

    log = m2.lines(a.log)
    arr = [l for l in log if l.startswith("ARR ") and not l.startswith("ARR STATE")]
    want_cmds = [c.split()[0] for c in COMMANDS if c != "arr-state"]
    got_cmds = [l.split()[1] for l in arr]
    check(got_cmds == want_cmds, f"ARR command lines {len(got_cmds)} in order, expected {len(want_cmds)}")
    bad = [l for l in arr if not l.endswith(" ok")]
    check(not bad, f"every row command ok (undo = one step each): {bad[:3] if bad else 'yes'}")
    states = [m2.kv(l) for l in log if l.startswith("ARR STATE ")]
    _, _, table = expected(44100.0, 120.0)
    starts16 = ",".join(str(x) for x in table)
    check(len(states) == 2, f"ARR STATE lines {len(states)}, expected 2 (before and after the render)")
    for i, s in enumerate(states):
        check(s.get("rows") == "5" and s.get("list") == LIST and s.get("starts16") == starts16,
              f"ARR STATE {i + 1}: rows={s.get('rows')} list={s.get('list')} starts16={s.get('starts16')}, "
              f"expected {LIST} / {starts16}")
    if len(states) == 2:
        check(states[0].get("play") == "0" and states[1].get("play") == "1", "song mode off, then on (arr-play 1)")
    check(any(l == "RENDER song rows=5" for l in log), "RENDER song rows=5")
    r = [m2.kv(l) for l in log if l.startswith("RENDER file=")]
    check(r, "rendered")
    if not r:
        print("arr check: FAILED")
        return 1
    rate, tempo0 = float(r[-1]["rate"]), float(r[-1]["tempo"])
    rows, end, table = expected(rate, tempo0)
    want_sw = [(f, SONG[i][0], SONG[i][1]) for f, i in rows] + [((end // 64 + 1) * 64, 1, 1)]
    got_sw = [(int(d["frame"]), int(d["scene"]), int(d["pattern"]))
              for d in (m2.kv(l) for l in log if l.startswith("RENDER switch "))]
    check(got_sw == want_sw, f"switch frames (frame, scene, pattern) {got_sw}, expected the row starts {want_sw}")
    songrows = [m2.kv(l) for l in log if l.startswith("RENDER song row=")]
    want_rows = [(1, 0, 0)] + [(i + 1, table[i], (f // 64) * 64) for f, i in rows]
    got_rows = [(int(d["row"]), int(d["pos16"]), int(d["block"])) for d in songrows]
    check(got_rows == want_rows, f"song position at each row start (row, SPP, block) {got_rows}, expected {want_rows}")
    ends = [int(m2.kv(l)["block"]) for l in log if l.startswith("RENDER song end ")]
    check(ends == [(end // 64) * 64], f"song end in block {ends}, expected [{(end // 64) * 64}] (end frame {end})")
    loads = [m2.kv(l) for l in log if l.startswith("LOAD ")]
    check(loads and int(loads[-1]["xruns"]) == 0, f"live engine: xruns {loads[-1]['xruns'] if loads else '?'}")
    print("arr check:", "OK" if ok else "FAILED")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--out", required=True)
    s.add_argument("--out-dir", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--log", required=True)
    a = ap.parse_args()
    return script_cmd(a) if a.cmd == "script" else verify_cmd(a)


if __name__ == "__main__":
    sys.exit(main())
