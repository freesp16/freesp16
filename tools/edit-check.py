#!/usr/bin/env python3
"""The pattern edit smoke check on the Linux desktop (run by scripts/host-smoke.sh CHECK=edit). Two subcommands:

  tools/edit-check.py script --out FILE --out-dir DIR
      writes one scripted-input session (ScriptedInput format, io/controllers/ScriptedInput.h), with the generated kit
      on scene 1: pad 1 selects track 1; the step keys enter FULL steps 1, 5, 10 in pattern 1; `cmd edit-copy pattern
      1 1` + `cmd edit-paste pattern 1 2` (the SceneEditor, the paste prepared on a worker); the panel step gesture:
      hold ext.copy + step keys 1 and 5, then in pattern 4 hold ext.paste + step key 3 (pasted to steps 3 and 7);
      back to pattern 1; the chain gesture in PATTERN mode: hold step key 1 (the current pattern), press 2, 2, 4,
      release; `cmd state`; `cmd render DIR/edit.wav 11 chain` (offline, the chain instead of the scene queue); quit.
      Every action is ordered by the UI thread (the render first waits for pending pastes), so the script's gaps only
      need to cover the stopped transport's immediate switches (a few UI frames).

  tools/edit-check.py verify --log LOG --render WAV
      one line per check, exit 1 when one fails:
        - EDIT pasted pattern 1 2 ok; EDIT CHAIN scene=1 patterns=1,2,2,4
        - M2 PATTERN lines: pattern 2 has pattern 1's cells (F1.1,F5.1,F10.1), pattern 4 has F3.1,F7.1
        - RENDER chain=1,2,2,4 and the RENDER switch frames: the pass ends (16 steps at the render tempo) with patterns
          2, 4, 1, 2 — the repeat of pattern 2 is a wrap, no switch (SCN-031)
        - onsets on MAIN of the render (tools/m2-check.py's detector): one per FULL step of each pass of the chain
          (pattern 2 = the pasted copy, pattern 4 = the pasted steps), within 5 ms, no others
Standard library only."""
import argparse
import importlib.util
import math
import pathlib
import sys

_spec = importlib.util.spec_from_file_location("m2check", pathlib.Path(__file__).with_name("m2-check.py"))
m2 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(m2)

CHAIN = [1, 2, 2, 4]
P1_STEPS = [1, 5, 10]
P4_STEPS = [3, 7]


def script_cmd(a) -> int:
    ev = []
    t = 3000

    def at(ms, line):
        ev.append((ms, line))

    def key(name, gap=90):
        nonlocal t
        at(t, f"press {name}")
        at(t + 40, f"release {name}")
        t += gap

    def cmd(text, gap=150):
        nonlocal t
        at(t, f"cmd {text}")
        t += gap

    def pattern(n):
        key("pattern")
        key(f"step{n}")
        t_wait(400)  # stopped: the switch is immediate; its SwitchDone reaches the model / the keys' playhead
        key("pattern", 200)

    def t_wait(ms):
        nonlocal t
        t += ms

    def hold(name, keys):
        nonlocal t
        at(t, f"press {name}")
        t += 60
        for k in keys:
            key(f"step{k}", 120)
        at(t, f"release {name}")
        t += 200

    cmd("trigger-type full")
    pattern(1)
    key("pad1", 300)  # selects track 1 (and plays it)
    for s in P1_STEPS:
        key(f"step{s}")
    t_wait(200)
    cmd("edit-copy pattern 1 1")
    cmd("edit-paste pattern 1 2", 400)
    hold("ext.copy", [1, 5])
    pattern(4)
    hold("ext.paste", [3])
    pattern(1)
    # SCN-030: hold the current pattern's key in PATTERN mode and press the others.
    key("pattern")
    at(t, "press step1")
    t += 100
    for k in CHAIN[1:]:
        key(f"step{k}", 120)
    at(t, "release step1")
    t += 150
    key("pattern", 300)
    cmd("state", 300)
    cmd(f"render {a.out_dir}/edit.wav 11 chain", 1000)
    at(t, "quit")  # runs after the render (the UI thread renders synchronously)
    with open(a.out, "w") as f:
        f.write("# generated by tools/edit-check.py script (time 0 = the app's first frame)\n")
        for ms, line in sorted(ev, key=lambda e: e[0]):
            f.write(f"{ms} {line}\n")
    return 0


def expected(rate, bpm, total):
    """Switch frames (pattern) and FULL onset frames of the chain from PPQ 0 at frame 0 (64-frame blocks, frameAt)."""
    ppf = bpm / (60.0 * rate)
    frame = lambda q: int(q / ppf + 1e-6)
    switches, onsets = [], []
    q, i, prev = 0.0, 0, None
    while frame(q) < total:
        pat = CHAIN[i % len(CHAIN)]
        if prev is not None and pat != prev:
            switches.append((frame(q), pat))
        for s in (P4_STEPS if pat == 4 else P1_STEPS):
            t = frame(q + (s - 1) * 0.25)
            if t < total:
                onsets.append(t)
        prev = pat
        q += 16 * 0.25
        i += 1
    return switches, onsets


def verify_cmd(a) -> int:
    ok = True

    def check(cond, text):
        nonlocal ok
        ok = ok and bool(cond)
        print(("PASS " if cond else "FAIL ") + text)

    log = m2.lines(a.log)
    check(any(l.startswith("EDIT pasted pattern 1 2 ok") for l in log), "EDIT pasted pattern 1 2 ok (worker paste)")
    check(any(l == "EDIT CHAIN scene=1 patterns=1,2,2,4" for l in log), "EDIT CHAIN scene=1 patterns=1,2,2,4 (keys)")
    _, pats = m2.state_after(log, None)
    by = {}
    for l in pats:
        d = m2.kv(l)
        by[(int(d["scene"]), int(d["pattern"]))] = d.get("cells", "")
    want1 = ",".join(f"F{s}.1" for s in P1_STEPS)
    want4 = ",".join(f"F{s}.1" for s in P4_STEPS)
    check(by.get((1, 1)) == want1, f"pattern 1 cells {by.get((1, 1))} (step keys), expected {want1}")
    check(by.get((1, 2)) == want1, f"pattern 2 cells {by.get((1, 2))} (pasted pattern 1)")
    check(by.get((1, 4)) == want4, f"pattern 4 cells {by.get((1, 4))} (ext.copy / ext.paste), expected {want4}")
    check(any(l == "RENDER chain=1,2,2,4" for l in log), "RENDER chain=1,2,2,4")
    r = [m2.kv(l) for l in log if l.startswith("RENDER file=")]
    check(r, "rendered")
    if not r:
        print("edit check: FAILED")
        return 1
    rate, total, bpm = float(r[-1]["rate"]), int(r[-1]["frames"]), float(r[-1]["tempo"])
    exp_sw, exp_on = expected(rate, bpm, total)
    got_sw = [(int(m2.kv(l)["frame"]), int(m2.kv(l)["pattern"])) for l in log if l.startswith("RENDER switch ")]
    check(got_sw == exp_sw, f"switch frames (frame, pattern) {got_sw}, expected the pass ends {exp_sw}")
    rr, main = m2.read_main(a.render)
    got = m2.detect_onsets(main, rr)
    tol = int(0.005 * rr)
    missing = [e for e in exp_on if not any(abs(g - e) <= tol for g in got)]
    extra = [g for g in got if not any(abs(g - e) <= tol for e in exp_on)]
    check(not missing and not extra and len(exp_on) > 10,
          f"onsets on MAIN: {len(got)} found, {len(exp_on)} expected (chain passes), missing {missing[:4]}, "
          f"extra {extra[:4]}")
    loads = [m2.kv(l) for l in log if l.startswith("LOAD ")]
    check(loads and int(loads[-1]["xruns"]) == 0, f"live engine: xruns {loads[-1]['xruns'] if loads else '?'}")
    print("edit check:", "OK" if ok else "FAILED")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--out", required=True)
    s.add_argument("--out-dir", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--log", required=True)
    v.add_argument("--render", required=True)
    a = ap.parse_args()
    return script_cmd(a) if a.cmd == "script" else verify_cmd(a)


if __name__ == "__main__":
    sys.exit(main())
