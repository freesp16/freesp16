#!/usr/bin/env python3
"""The project import host smoke check (scripts/smoke/94-import.sh, CHECK=import): a generated reference project is
imported by the app, played offline and its onsets checked. Two subcommands:

  tools/prj-dump/import-smoke.py script --out-dir DIR
      generates tests/unit/interop/synthetic/basic.json into DIR/disk (prj-synth.py: Projects/Basic.prj, System/
      data.rsm, Samples/kick.wav + tone.wav with .wav.dat), records a hash of every file there (DIR/source.json) and
      writes DIR/script.txt: `cmd import-sp16 <prj>`, `cmd render DIR/import.wav 3`, quit.

  tools/prj-dump/import-smoke.py verify --log LOG --out-dir DIR
      one line per check, exit 1 when one fails:
        - IMPORT done ok, the report's content / samples / roundtrip lines (16 scenes, 256 tracks, 64 patterns,
          6 triggers, 1 lock; 2 samples found, 0 missing; tree identical), PROJECT … samples=2 loaded=2 missing=0
        - M2 PATTERN scene=1 pattern=1: length 16, full=6, the six cells of the description, one lock cell
        - the render (scene 1 pattern 1 at 120 BPM, then the empty scenes 2-4, where the engine's fallback test tone
          sounds): the switch to scene 2 at the pass end (frame 88200), onsets on MAIN in the first pass exactly at
          the six FULL step times (+/- 5 ms, none extra), the step-9 hit (volume lock 40 vs track volume 100) at least 3 dB
          below the other kick hits
        - the source tree is unchanged (FMT-045: same files, same hashes, nothing added), the live engine xruns 0
Standard library only."""
import argparse
import hashlib
import importlib.util
import json
import math
import pathlib
import subprocess
import sys

here = pathlib.Path(__file__).resolve().parent
repo = here.parent.parent
_spec = importlib.util.spec_from_file_location("m2check", repo / "tools" / "m2-check.py")
m2 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(m2)

BPM, STEP_S = 120.0, 60.0 / 120.0 / 4
KICK_STEPS, TONE_STEPS, LOCKED_STEP = [0, 4, 8, 12], [2, 10], 8


def tree_hash(root):
    out = {}
    for p in sorted(pathlib.Path(root).rglob("*")):
        if p.is_file():
            out[str(p.relative_to(root))] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


def script_cmd(a):
    out = pathlib.Path(a.out_dir)
    disk = out / "disk"
    res = subprocess.run([sys.executable, str(here / "prj-synth.py"),
                          str(repo / "tests" / "unit" / "interop" / "synthetic" / "basic.json"), str(disk)],
                         capture_output=True, text=True, check=True)
    prj = res.stdout.strip().splitlines()[-1]
    (out / "source.json").write_text(json.dumps({"prj": prj, "files": tree_hash(disk)}, indent=1))
    with open(a.out if a.out else out / "script.txt", "w") as f:
        f.write("# generated by tools/prj-dump/import-smoke.py script (time 0 = the app's first frame)\n")
        f.write(f"3000 cmd import-sp16 {prj}\n")
        f.write(f"9000 cmd render {out}/import.wav 3\n")
        f.write("9500 cmd state\n")
        f.write("10500 quit\n")
    print(prj)
    return 0


def verify_cmd(a):
    out = pathlib.Path(a.out_dir)
    tag_lines = m2.lines(a.log)
    ok = True

    def check(cond, text):
        nonlocal ok
        print(("  OK   " if cond else "  FAIL ") + text)
        ok = ok and bool(cond)

    def has(prefix):
        return [l for l in tag_lines if l.startswith(prefix)]

    done = has("IMPORT done ")
    check(done and " ok " in done[-1] + " ", f"import finished ok: {done[-1] if done else 'no IMPORT done line'}")
    content = has("IMPORT content ")
    check(content and "scenes=16 tracks=256 patterns=64" in content[-1] and "triggers=6 lockCells=1 locks=1"
          in content[-1], f"report content: {content[-1] if content else '-'}")
    samples = has("IMPORT samples ")
    check(samples and "referenced=2 found=2 missing=0" in samples[-1] and "wavdat=2" in samples[-1],
          f"report samples: {samples[-1] if samples else '-'}")
    rt = has("IMPORT roundtrip ")
    check(rt and "identical" in rt[-1], f"tree round trip: {rt[-1] if rt else '-'}")
    proj = [l for l in has("PROJECT ") if "samples=" in l]
    check(proj and "samples=2 loaded=2 missing=0" in proj[-1], f"project open: {proj[-1] if proj else '-'}")
    pats = [l for l in has("M2 PATTERN scene=1 pattern=1 ")]
    want = ",".join(sorted([f"F{s + 1}.1{'L' if s == LOCKED_STEP else ''}" for s in KICK_STEPS] +
                           [f"F{s + 1}.2" for s in TONE_STEPS], key=lambda c: (int(c[1:].split('.')[0]), c)))
    if pats:
        kv = m2.kv(pats[-1])
        cells = kv.get("cells", "")
        got = ",".join(sorted(cells.split(","), key=lambda c: (int(c[1:].split('.')[0]), c)))
        check(kv.get("length") == "16" and kv.get("full") == "6" and kv.get("locks") == "1" and got == want,
              f"pattern 1.1: {pats[-1]} (want cells {want})")
    else:
        check(False, "no M2 PATTERN scene=1 pattern=1 line")
    render = [l for l in has("RENDER file=")]
    check(render, f"render: {render[-1] if render else 'no RENDER line'}")
    wav = out / "import.wav"
    if wav.exists():
        rate, main = m2.read_main(str(wav))
        # The first pass only: at the switch to scene 2 (empty, no samples) the engine's fallback test tone starts.
        switch = [m2.kv(l) for l in has("RENDER switch scene=2 ")]
        end = int(switch[0]["frame"]) if switch else len(main)
        check(end == int(round(16 * STEP_S * rate)), f"scene 2 queued at the end of the 16-step pass (frame {end})")
        onsets = [o for o in m2.detect_onsets(main, rate) if o < end - 64]  # the switch frame is block-quantised
        expect = sorted(int(round(s * STEP_S * rate)) for s in KICK_STEPS + TONE_STEPS)
        times = [f"{o / rate:.3f}" for o in onsets]
        good = len(onsets) == len(expect) and all(abs(o - e) <= 0.005 * rate for o, e in zip(onsets, expect))
        check(good, f"onsets on MAIN at the FULL step times +/- 5 ms: got {times}, want "
                    f"{[f'{e / rate:.3f}' for e in expect]}")

        def peak(step):
            s0 = int(step * STEP_S * rate)
            return max(abs(x) for x in main[s0:s0 + int(0.1 * rate)])

        kicks = [peak(s) for s in KICK_STEPS if s != LOCKED_STEP]
        locked = peak(LOCKED_STEP)
        drop = 20 * math.log10(max(locked, 1e-9) / max(min(kicks), 1e-9))
        check(drop <= -3.0, f"volume lock on step 9: {drop:+.1f} dB vs the other kicks (want <= -3 dB)")
    else:
        check(False, "no render WAV")
    src = json.loads((out / "source.json").read_text())
    check(tree_hash(out / "disk") == src["files"], f"source tree unchanged ({len(src['files'])} files, FMT-045)")
    audio = [l for l in tag_lines if l.startswith("AUDIO alsa_periods=") or l.startswith("LOAD ")]
    check(audio and all(" xruns=0 " in l + " " for l in audio[-2:]), "live engine xruns=0")
    print("import checks:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--out-dir", required=True)
    s.add_argument("--out")
    v = sub.add_parser("verify")
    v.add_argument("--log", required=True)
    v.add_argument("--out-dir", required=True)
    a = ap.parse_args()
    return script_cmd(a) if a.cmd == "script" else verify_cmd(a)


if __name__ == "__main__":
    sys.exit(main())
