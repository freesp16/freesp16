#!/usr/bin/env python3
"""Generate the C++ theme header from the design tokens (spec 07-ui-design/tokens.json, W3C token format).

  tools/gen_theme.py <tokens.json> <out.h>

Every component reads colours, type styles, spacing, radii and durations from the generated header only (UID-050).
The generator is strict: a missing token the UI depends on, or an unknown token in a known group, is an error, so a
spec change cannot silently drop or add a colour. Colours become 0xAARRGGBB constants (straight alpha).
"""
import json
import pathlib
import re
import sys

COLOUR_KEYS = ["bg", "surface-1", "surface-2", "surface-3", "overlay", "border", "border-strong", "text-1", "text-2",
               "text-3", "accent", "accent-weak", "on-accent", "mod", "play", "rec", "warn", "playhead"]
DARK_ONLY = ["meter-low", "meter-mid", "meter-high"]
TEXT_STYLES = ["caption", "label", "body", "body-strong", "title", "value-s", "value", "value-l", "display"]
RADII = ["xs", "s", "m", "l", "pill"]
MOTION = ["instant", "fast", "base", "slow", "meter-release", "peak-hold", "pad-flash", "blink-slow", "blink-fast"]
SIZES = ["hit-min", "icon", "icon-s", "focus-ring-offset", "status-row", "context-bar", "knob-strip", "rail"]
BORDERS = ["hairline", "focus", "track-frame"]
GROUPS = ["meta", "color", "font", "space", "radius", "border", "elevation", "motion", "size"]
COLOUR_GROUPS = ["dark", "light", "classic", "track", "scene"]
FONT_GROUPS = ["family", "feature", "style"]
ELEVATIONS = ["0", "1", "2"]
SHADOW = re.compile(r"(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+(?:(\d+)(?:px)?\s+)?(#[0-9A-Fa-f]{6,8})")
BEZIER = re.compile(r"cubic-bezier\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)")


def ident(name: str) -> str:
    parts = re.split(r"[-_ ]", name)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return "n" + out if out[0].isdigit() else out


def argb(hexstr: str) -> str:
    h = hexstr.lstrip("#")
    if len(h) == 6:
        h += "FF"
    if not re.fullmatch(r"[0-9A-Fa-f]{8}", h):
        raise SystemExit(f"bad colour {hexstr!r}")
    return f"0x{h[6:8]}{h[0:6]}u".upper().replace("0X", "0x").replace("U", "u")


def need(obj: dict, key: str, where: str):
    if key not in obj:
        raise SystemExit(f"tokens: missing {where}.{key}")
    return obj[key]


def check_known(obj: dict, known: list, where: str):
    extra = [k for k in obj if not k.startswith("$") and k not in known]
    if extra:
        raise SystemExit(f"tokens: unknown {where} token(s) {extra}: add them to tools/gen_theme.py and the theme")


def shadows(value: str, where: str) -> list:
    """CSS box-shadow list -> [(dx, dy, blur, spread, argb)]."""
    out = []
    for part in value.split(","):
        m = SHADOW.fullmatch(part.strip())
        if not m:
            raise SystemExit(f"tokens: cannot parse {where} shadow {part.strip()!r}")
        dx, dy, blur, spread, colour = m.groups()
        out.append((int(dx), int(dy), int(blur), int(spread or 0), argb(colour)))
    return out


def main() -> int:
    src, dst = map(pathlib.Path, sys.argv[1:3])
    t = json.loads(src.read_text(encoding="utf-8"))
    check_known(t, GROUPS, "top-level")
    check_known(need(t, "color", ""), COLOUR_GROUPS, "color")
    check_known(need(t, "font", ""), FONT_GROUPS, "font")
    canvas = need(need(t, "meta", ""), "canvas", "meta")
    colour = need(t, "color", "")
    lines = ["// Generated by tools/gen_theme.py from " + src.name + ". Do not edit; do not commit.",
             "#pragma once", "#include <cstdint>", "", "namespace theme::tokens", "{",
             f"inline constexpr int canvasWidth = {canvas['width']};",
             f"inline constexpr int canvasHeight = {canvas['height']};", "",
             "struct Palette", "{"]
    lines += [f"    std::uint32_t {ident(k)};" for k in COLOUR_KEYS + DARK_ONLY] + ["    bool classic = false;", "};", ""]
    for theme in ("dark", "light", "classic"):
        pal = need(colour, theme, "color")
        check_known(pal, COLOUR_KEYS + DARK_ONLY, f"color.{theme}")
        values = []
        for k in COLOUR_KEYS + DARK_ONLY:
            entry = pal.get(k) or (colour["dark"].get(k) if k in DARK_ONLY else None)
            if entry is None:
                raise SystemExit(f"tokens: missing color.{theme}.{k}")
            values.append(f"    {argb(entry['$value'])}, // {k}")
        if theme == "classic":
            values.append("    true, // classic control geometry")
        lines += [f"inline constexpr Palette {theme} {{"] + values + ["};", ""]
    track = need(colour, "track", "color")
    lines += ["struct TrackColour", "{", "    std::uint32_t base, dim;", "    int hue;", "};",
              "inline constexpr TrackColour track[16] = {"]
    for i in range(1, 17):
        e = need(track, str(i), "color.track")
        lines.append(f"    {{{argb(e['$value'])}, {argb(e['dim'])}, {e['hue']}}}, // track {i}")
    lines += ["};", ""]
    styles = need(need(t, "font", ""), "style", "font")
    check_known(styles, TEXT_STYLES, "font.style")
    lines += ["struct TextStyle", "{", "    float size, line;", "    int weight;", "    float tracking;",
              "    bool upper, tabular;", "};"]
    for name in TEXT_STYLES:
        s = need(styles, name, "font.style")
        lines.append(f"inline constexpr TextStyle {ident(name)} {{{s['size']}.0f, {s['line']}.0f, {s['weight']}, "
                     f"{float(s.get('tracking', 0.0))}f, {str(s.get('case') == 'upper').lower()}, "
                     f"{str('tnum' in s.get('features', '')).lower()}}};")
    lines.append("")
    space = need(t, "space", "")
    lines.append("inline constexpr int space[] = {" + ", ".join(str(space[str(i)]) for i in range(len(space))) + "};")
    radius = need(t, "radius", "")
    check_known(radius, RADII, "radius")
    lines += [f"inline constexpr int radius{ident(k).capitalize()} = {radius[k]};" for k in RADII]
    border = need(t, "border", "")
    check_known(border, BORDERS, "border")
    lines += [f"inline constexpr int border{ident(k)[0].upper() + ident(k)[1:]} = {need(border, k, 'border')};"
              for k in BORDERS]
    # Elevation (02-tokens.md "Elevation"): level 1 = a bottom edge, level 2 = drop shadow + 1 lpx border.
    elevation = need(t, "elevation", "")
    check_known(elevation, ELEVATIONS, "elevation")
    e1 = shadows(need(need(elevation, "1", "elevation"), "$value", "elevation.1"), "elevation.1")[0]
    e2 = shadows(need(need(elevation, "2", "elevation"), "$value", "elevation.2"), "elevation.2")
    drop = next(x for x in e2 if x[2] > 0)
    ring = next((x for x in e2 if x[2] == 0 and x[3] > 0), None)
    if ring is None:
        raise SystemExit("tokens: elevation.2 needs a 0 0 0 <n>px border ring")
    lines += [f"inline constexpr int elevation1EdgeY = {e1[1]};", f"inline constexpr std::uint32_t elevation1Edge = {e1[4]};",
              f"inline constexpr int elevation2OffsetY = {drop[1]};", f"inline constexpr int elevation2Blur = {drop[2]};",
              f"inline constexpr std::uint32_t elevation2Shadow = {drop[4]};",
              f"inline constexpr int elevation2Border = {ring[3]};",
              f"inline constexpr std::uint32_t elevation2BorderColour = {ring[4]};"]
    motion = need(t, "motion", "")
    check_known(motion, MOTION, "motion")
    easing = None
    for k in MOTION:
        m = need(motion, k, "motion")
        value = m.get("duration", m.get("period"))
        if value is None:
            raise SystemExit(f"tokens: motion.{k} has neither duration nor period")
        lines.append(f"inline constexpr int motion{ident(k)[0].upper() + ident(k)[1:]}Ms = {value};")
        if "easing" in m:
            b = BEZIER.fullmatch(m["easing"])
            if not b:
                raise SystemExit(f"tokens: motion.{k}.easing {m['easing']!r} is not a cubic-bezier")
            if easing is not None and easing != b.groups():
                raise SystemExit("tokens: motion easings differ; the theme supports one standard curve")
            easing = b.groups()
    if easing is None:
        raise SystemExit("tokens: no motion easing")
    lines.append("inline constexpr float motionEase[4] = {" + ", ".join(f"{float(v)}f" for v in easing) + "};")
    size = need(t, "size", "")
    check_known(size, SIZES, "size")
    lines += [f"inline constexpr int size{ident(k)[0].upper() + ident(k)[1:]} = {size[k]};" for k in SIZES]
    lines += ["} // namespace theme::tokens", ""]
    dst.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    if not dst.exists() or dst.read_text(encoding="utf-8") != text:
        dst.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
