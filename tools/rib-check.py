#!/usr/bin/env python3
"""The touch strip smoke check on the Linux desktop (run by scripts/host-smoke.sh CHECK=rib). Two subcommands:

  tools/rib-check.py script --out FILE
      writes one scripted-input session (ScriptedInput format, io/controllers/ScriptedInput.h) with the generated kit
      (tools/gen-test-kit.py: 0.10 s one-shots) on scene 1, the transport stopped (REPEAT free-runs, 120 BPM):
        A  MODE once (PITCH -> REPEAT); hold pad 1, `strip 40` (the 1/8 zone) for 2 s, `strip off`, release the pad
        B  HOLD on; hold pad 2, `strip 80` (1/16) for 0.5 s, `strip off` (HOLD keeps the rate), 1 s later release
           pad 2 (the repeats stop: only while a pad is held); HOLD off
        C  MODE three times (REPEAT -> USER1 -> USER2 -> PITCH); `cmd ribbon-assign 1 1 track.volume`,
           `cmd ribbon-range 1 1 0.2 0.9`, `cmd ribbon` (the TOUCH STRIP SETTING commands and their project state)
      The strip events come from the script (source virtual), so the app's io::StripRouter posts them to the engine
      like the linux window's Ctrl + wheel; the device's reader thread is the same message from another thread.

  tools/rib-check.py verify --log LOG --wav WAV
      one line per check, exit 1 when one fails:
        - RIBBON lines: mode REPEAT, touch 40 with leds=0x0c (the 1/8 zone's two LEDs), HOLD on/off, the MODE cycle
          back to PITCH with HOLD cancelled, RIBBON STATE with the assigned item U1.1=track.volume:0.200-0.900
        - LAMP lines (lamp_log=1): stripmode.repeat lit, strip.led.3 + strip.led.4 lit (and no other strip LED) while
          the strip is touched in the 1/8 zone, strip.hold lit under HOLD
        - onsets on MAIN (WAV channels 0/1): A = the pad hit + repeats 250 ms apart (+/- 2 ms: the engine's free run is
          sample-exact, the detector's jitter is a sample or two), at least 6; B = repeats 125 ms apart (+/- 2 ms),
          at least 3 of them after the strip was lifted (HOLD), none later than 150 ms after the pad release
      Not checked here: PITCH and USER audibly (they go through the LFO's ModMatrix; tests/unit/ribbon covers the
      contributions, and test_ribbon_wiring.cpp the +200 cents on MAIN once the matrix is merged), the device strip
      (a hardware check).
Standard library only."""
import argparse
import math
import re
import struct
import sys
import wave

TAG = re.compile(r"\[sp16-mod\] \S+ (.*)$")

A_PAD, A_TOUCH, A_LIFT, A_RELEASE = 3200, 3400, 5400, 5600
B_HOLD, B_PAD, B_TOUCH, B_LIFT, B_RELEASE, B_HOLD_OFF = 6400, 6600, 6700, 7200, 8200, 8600


def script_cmd(a) -> int:
    lines = [
        "# generated by tools/rib-check.py (time 0 = the app's first frame)",
        "3000 press strip.mode", "3040 release strip.mode",
        f"{A_PAD} press pad1 100", f"{A_TOUCH} strip 40", f"{A_LIFT} strip off", f"{A_RELEASE} release pad1",
        "6000 cmd ribbon",
        f"{B_HOLD} press strip.hold", f"{B_HOLD + 40} release strip.hold",
        f"{B_PAD} press pad2 100", f"{B_TOUCH} strip 80", f"{B_LIFT} strip off", f"{B_RELEASE} release pad2",
        f"{B_HOLD_OFF} press strip.hold", f"{B_HOLD_OFF + 40} release strip.hold",
        "9000 press strip.mode", "9040 release strip.mode",
        "9200 press strip.mode", "9240 release strip.mode",
        "9400 press strip.mode", "9440 release strip.mode",
        "9600 cmd ribbon-assign 1 1 track.volume", "9700 cmd ribbon-range 1 1 0.2 0.9", "9900 cmd ribbon",
        "10500 quit",
    ]
    with open(a.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    return 0


def log_lines(path):
    out = []
    with open(path, errors="replace") as f:
        for raw in f:
            m = TAG.search(raw.rstrip("\n"))
            if m:
                out.append(m.group(1))
    return out


def onsets(path, gate_dbfs=-40.0, quiet_ms=10.0):
    with wave.open(path, "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width != 2:
        raise SystemExit(f"{path}: {width * 8}-bit samples not supported")
    data = struct.unpack("<%dh" % (len(raw) // 2), raw)
    gate = 32768.0 * 10 ** (gate_dbfs / 20.0)
    quiet = int(rate * quiet_ms / 1000.0)
    found, below = [], quiet
    for i in range(len(data) // ch):
        v = max(abs(data[i * ch]), abs(data[i * ch + 1]) if ch > 1 else 0)
        if v >= gate:
            if below >= quiet:
                found.append(i / rate)
            below = 0
        else:
            below += 1
    return found, len(data) / ch / rate


def verify_cmd(a) -> int:
    ok = True

    def check(cond, text):
        nonlocal ok
        print(("  OK   " if cond else "  FAIL ") + text)
        ok = ok and bool(cond)

    lines = log_lines(a.log)
    rib = [l for l in lines if l.startswith("RIBBON ")]
    for l in rib:
        print("  " + l)
    check(any(l.startswith("RIBBON mode mode=REPEAT hold=0") for l in rib), "MODE: PITCH -> REPEAT")
    check(any(re.match(r"RIBBON touch 40 source=\d+ mode=REPEAT hold=0 leds=0x0c", l) for l in rib),
          "strip 40 in REPEAT: the 1/8 zone's two LEDs (0x0c)")
    check(any(l.startswith("RIBBON hold mode=REPEAT hold=1") for l in rib), "HOLD on")
    check(any(re.match(r"RIBBON release 80 source=\d+ mode=REPEAT hold=1 leds=0x30", l) for l in rib),
          "strip lifted under HOLD: the 1/16 zone stays lit (0x30)")
    check(any(l.startswith("RIBBON hold mode=REPEAT hold=0 leds=0x00") for l in rib), "HOLD off: LEDs dark")
    modes = [re.match(r"RIBBON mode mode=(\S+)", l).group(1) for l in rib if l.startswith("RIBBON mode ")]
    check(modes == ["REPEAT", "USER1", "USER2", "PITCH"], f"MODE cycle {modes}")
    check(any("RIBBON STATE mode=PITCH hold=0" in l and "items=U1.1=track.volume:0.200-0.900" in l for l in rib),
          "RIBBON STATE: USER1 item 1 = track.volume 0.200-0.900 (ribbon-assign / ribbon-range)")
    check(not any(l.startswith("CMD ") and "nothing to change" in l for l in lines), "every ribbon command applied")

    # Lamps: replay the LAMP lines into a state map.
    state, seen_zone, seen_mode, seen_hold = {}, False, False, False
    for l in lines:
        if not l.startswith("LAMP "):
            continue
        for item in l[5:].split():
            name, _, val = item.partition("=")
            state[name] = val.split("/")[-1] != "0"
        leds = {n for n, lit in state.items() if n.startswith("strip.led.") and lit}
        seen_zone = seen_zone or leds == {"strip.led.3", "strip.led.4"}
        seen_mode = seen_mode or state.get("stripmode.repeat", False)
        seen_hold = seen_hold or state.get("strip.hold", False)
    check(seen_mode, "LAMP stripmode.repeat lit")
    check(seen_zone, "LAMP strip.led.3 + strip.led.4 lit alone (1/8 zone)")
    check(seen_hold, "LAMP strip.hold lit")

    found, length = onsets(a.wav)
    print(f"  {a.wav}: {length:.1f} s, {len(found)} onsets")
    # The script clock vs the WAV: anchor on the first onset after 3.0 s (pad 1's hit at A_PAD).
    first = next((t for t in found if t >= 2.5), None)
    check(first is not None, "pad 1's hit on MAIN")
    if first is None:
        return 1
    shift = first - A_PAD / 1000.0
    print(f"  script clock vs WAV: {shift * 1000:+.0f} ms")

    def window(t0_ms, t1_ms):
        return [t for t in found if t0_ms / 1000.0 + shift - 0.02 <= t < t1_ms / 1000.0 + shift + 0.02]

    a_hits = window(A_PAD, A_RELEASE + 300)
    reps = a_hits[1:]
    gaps = [(reps[i] - reps[i - 1]) * 1000.0 for i in range(1, len(reps))]
    print("  A onsets: " + ", ".join(f"{t:.3f}" for t in a_hits))
    check(len(reps) >= 6, f"A: {len(reps)} repeats after the pad hit (>= 6)")
    check(gaps and all(abs(g - 250.0) <= 2.0 for g in gaps),
          "A: repeats 250 ms apart (+/- 2 ms): " + ", ".join(f"{g:.1f}" for g in gaps))
    check(all(t < A_LIFT / 1000.0 + shift + 0.15 for t in reps), "A: no repeat after the strip was lifted (no HOLD)")

    b_hits = window(B_PAD, B_HOLD_OFF)
    b_reps = b_hits[1:]
    b_gaps = [(b_reps[i] - b_reps[i - 1]) * 1000.0 for i in range(1, len(b_reps))]
    print("  B onsets: " + ", ".join(f"{t:.3f}" for t in b_hits))
    check(b_gaps and all(abs(g - 125.0) <= 2.0 for g in b_gaps),
          "B: repeats 125 ms apart (+/- 2 ms): " + ", ".join(f"{g:.1f}" for g in b_gaps))
    after_lift = [t for t in b_reps if t > B_LIFT / 1000.0 + shift + 0.05]
    check(len(after_lift) >= 3, f"B: {len(after_lift)} repeats after the strip was lifted under HOLD (>= 3)")
    check(all(t < B_RELEASE / 1000.0 + shift + 0.15 for t in b_reps), "B: none after the pad release")
    late = [t for t in found if t > B_HOLD_OFF / 1000.0 + shift + 0.05]
    check(not late, f"nothing after HOLD off ({len(late)} onsets)")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--out", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--log", required=True)
    v.add_argument("--wav", required=True)
    a = ap.parse_args()
    return script_cmd(a) if a.cmd == "script" else verify_cmd(a)


if __name__ == "__main__":
    sys.exit(main())
