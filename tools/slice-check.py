#!/usr/bin/env python3
"""The slice smoke check on the Linux desktop (run by scripts/host-smoke.sh CHECK=slice). Two subcommands:

  tools/slice-check.py script --out FILE --out-dir DIR
      writes one scripted-input session (ScriptedInput format, io/controllers/ScriptedInput.h), with the generated kit
      on scene 1 (track 1 = a 0.10 s tone, 4410 frames): pad 1 selects track 1; SLICE pad mode on; `cmd slice count 8`
      (GRID SLICE: 8 slices of 551 frames) and `cmd slice move 3 1202` (slice 3's start 100 frames later: slice 2
      grows, slice 3 shrinks); then, in SLICE pad mode, a pad hit followed by a step key four times — pads 5, 3, 2, 8 →
      steps 1, 5, 9, 13 (step entry writes the last-played slice as the slice-number lock, SLC-005); a recorded pass
      (REC + PLAY) with pads 6 and 7 on steps 3 and 11 (the recorder writes the hits' slice locks); `cmd slice state`;
      `cmd state`; `cmd render DIR/slice.wav 4` (offline, the app's engine with the posted slice tables); quit.

  tools/slice-check.py verify --log LOG --render WAV --kit-dir DIR --kit-json KIT.json
      one line per check, exit 1 when one fails:
        - SLICE line: 8 slices with points 0,551,1202,1653,… (the moved point) and one edited point
        - the pad hits logged as slices 5, 3, 2, 8, 6, 7 (INPUT padN slice=K)
        - the recorder's slice locks logged: step 3 = slice 6, step 11 = slice 7 (SLICE recorded …)
        - M2 PATTERN scene=1 pattern=1: entered cells F1.1L,F5.1L,F9.1L,F13.1L and recorded cells on steps 3 and 11,
          each with a lock (its slice)
        - onsets on MAIN of the first pass (until the render's first scene switch) with tools/m2-check.py's detector:
          one per entered step, at the step's frame (±3 ms), plus the recorded ones (±15 ms: their micro-timing)
        - slice boundaries: after each step's frame t0 the render is the slice's frames of the sample, sample-accurate
          — the best lag within ±4 frames is 0 (recorded steps: within ±15 ms, their offset), the level-matched residual
          ≤ 2 % of the slice's RMS (16-bit WAVs) —
          and silence from the slice end on (the next slice is never played; < -60 dBFS)
        - live engine: xruns 0
Standard library only."""
import argparse
import importlib.util
import json
import math
import pathlib
import struct
import sys
import wave

_spec = importlib.util.spec_from_file_location("m2check", pathlib.Path(__file__).with_name("m2-check.py"))
m2 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(m2)

COUNT, MOVED_SLICE, MOVED_FRAME = 8, 3, 1202
STEPS = {1: 5, 5: 3, 9: 2, 13: 8}  # step (1-based) -> slice (1-based), entered by its pad
RECORDED = {3: 6, 11: 7}           # step -> slice, recorded live in SLICE pad mode


def script_cmd(a) -> int:
    ev = []
    t = 3000

    def at(ms, line):
        ev.append((ms, line))

    def key(name, gap=90):
        nonlocal t
        at(t, f"press {name}")
        at(t + 40, f"release {name}")
        t += gap

    def cmd(text, gap=150):
        nonlocal t
        at(t, f"cmd {text}")
        t += gap

    cmd("trigger-type full")
    key("pattern")
    key("step1")
    t += 400  # stopped: the switch is immediate
    key("pattern", 200)
    key("pad1", 300)  # PLAY mode: selects track 1 (and plays it)
    key("padmode.slice", 200)
    cmd(f"slice count {COUNT}")
    cmd(f"slice move {MOVED_SLICE} {MOVED_FRAME}", 300)
    for step, slice_ in STEPS.items():
        key(f"pad{slice_}", 150)  # SLICE mode: pad n plays slice n (area 1)
        key(f"step{step}", 150)   # step entry: the last-played slice becomes the step's slice lock
    # One recorded pass in SLICE pad mode (120 BPM: 125 ms a step): pads 6 and 7 on steps 3 and 11 — the recorder
    # writes each hit with the slice-number lock of the slice it played (SLC-005).
    key("rec", 400)
    play = t
    at(play, "press play")
    at(play + 40, "release play")
    for step, slice_ in RECORDED.items():
        at(play + (step - 1) * 125, f"press pad{slice_} 100")
        at(play + (step - 1) * 125 + 40, f"release pad{slice_}")
    t = play + 2150
    key("stop", 300)
    key("rec", 600)
    cmd("slice state")
    cmd("state", 300)
    cmd(f"render {a.out_dir}/slice.wav 4", 1000)
    at(t, "quit")
    with open(a.out, "w") as f:
        f.write("# generated by tools/slice-check.py script (time 0 = the app's first frame)\n")
        for ms, line in sorted(ev, key=lambda e: e[0]):
            f.write(f"{ms} {line}\n")
    return 0


def read_wav_mono(path):
    with wave.open(str(path), "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width != 2:
        raise SystemExit(f"{path}: {width * 8}-bit not supported")
    data = struct.unpack("<%dh" % (n * ch), raw[: n * ch * 2])
    if ch == 1:
        return rate, [x / 32768.0 for x in data]
    return rate, [(data[i * ch] + data[i * ch + 1]) / 65536.0 for i in range(n)]


def match(render, ref, t0, max_lag=4):
    """(lag, gain, residual / ref RMS) of the best fit of ref at t0 + lag: the lag of the highest normalised
    correlation (silence never fits), then the level-matched residual there."""
    best = None
    ref_e = sum(x * x for x in ref) or 1e-30
    for lag in range(-max_lag, max_lag + 1):
        s = t0 + lag
        if s < 0 or s + len(ref) > len(render):
            continue
        seg = render[s:s + len(ref)]
        dot = sum(x * y for x, y in zip(seg, ref))
        seg_e = sum(x * x for x in seg)
        corr = dot / math.sqrt(seg_e * ref_e) if seg_e > 0 else -1.0
        if best is None or corr > best[0]:
            g = dot / ref_e
            res = math.sqrt(sum((x - g * y) ** 2 for x, y in zip(seg, ref)) / ref_e) / (abs(g) or 1e-30)
            best = (corr, lag, g, res)
    return best[1:] if best else (None, 0.0, 1e9)


def verify_cmd(a) -> int:
    ok = True

    def check(cond, text):
        nonlocal ok
        ok = ok and bool(cond)
        print(("PASS " if cond else "FAIL ") + text)

    log = m2.lines(a.log)
    sl = [m2.kv(l) for l in log if l.startswith("SLICE scene=")]
    check(sl, "SLICE state logged")
    points = []
    if sl:
        d = sl[-1]
        points = [int(x) for x in d["points"].split(",")]
        frames = int(d["frames"])
        eq = [k * frames // COUNT for k in range(COUNT)] + [frames]
        want = list(eq)
        want[MOVED_SLICE - 1] = MOVED_FRAME
        check(int(d["count"]) == COUNT and points == want and int(d["edited"]) == 1,
              f"slices {d['count']} points {points}, expected {want} (GRID SLICE 8 + one moved point)")
    hits = [m2.kv(l) for l in log if l.startswith("INPUT pad") and "slice=" in l]
    got_slices = [int(h["slice"]) for h in hits]
    want_slices = list(STEPS.values()) + list(RECORDED.values())
    check(got_slices == want_slices, f"SLICE pad hits played slices {got_slices}, expected {want_slices}")
    rec = {int(m2.kv(l)["step"]): int(m2.kv(l)["slice"]) for l in log if l.startswith("SLICE recorded ")}
    check(rec == RECORDED, f"recorded hits with their slice locks {rec}, expected {RECORDED} (SLICE recorded …)")
    _, pats = m2.state_after(log, None)
    cells = {}
    for l in pats:
        d = m2.kv(l)
        cells[(int(d["scene"]), int(d["pattern"]))] = d.get("cells", "")
    got_cells = (cells.get((1, 1)) or "").split(",")
    entered = [c for c in got_cells if c.split(".")[0][1:] in {str(k) for k in STEPS}]
    recorded = [c for c in got_cells if c.split(".")[0][1:] in {str(k) for k in RECORDED}]
    check(entered == [f"F{k}.1L" for k in STEPS] and len(recorded) == len(RECORDED)
          and all(c.endswith("L") for c in recorded) and len(got_cells) == len(STEPS) + len(RECORDED),
          f"pattern 1 cells {cells.get((1, 1))}: entered F1/F5/F9/F13 and recorded steps 3/11, each with its slice lock")
    r = [m2.kv(l) for l in log if l.startswith("RENDER file=")]
    check(r, "rendered")
    if not r or len(points) != COUNT + 1:
        print("slice check: FAILED")
        return 1
    rate, total, bpm = float(r[-1]["rate"]), int(r[-1]["frames"]), float(r[-1]["tempo"])
    switches = [int(m2.kv(l)["frame"]) for l in log if l.startswith("RENDER switch ")]
    end = min(switches + [total])
    end -= end % 64  # scene 2 has no sample on track 1: the engine's temporary test tone starts at that block
    ppf = bpm / (60.0 * rate)
    exp = []
    q = 0.0
    while int(q / ppf + 1e-6) < end:
        for s, k in list(STEPS.items()) + list(RECORDED.items()):
            f = int((q + (s - 1) * 0.25) / ppf + 1e-6)
            if f < end:
                exp.append((f, k, s in RECORDED))
        q += 16 * 0.25
    exp.sort()
    rr, main = read_wav_mono(a.render)
    got = [g for g in m2.detect_onsets(main[:end], rr) if g < end]
    tol = lambda rec: int((0.015 if rec else 0.003) * rr)
    missing = [e for e, _, rec in exp if not any(abs(g - e) <= tol(rec) for g in got)]
    extra = [g for g in got if not any(abs(g - e) <= tol(rec) for e, _, rec in exp)]
    check(exp and not missing and not extra, f"onsets on MAIN: {len(got)} found, {len(exp)} expected, missing "
          f"{missing[:4]}, extra {extra[:4]}")
    manifest = json.load(open(a.kit_json))
    first = sorted(s["name"] for s in manifest["samples"])[0]
    _, sample = read_wav_mono(pathlib.Path(a.kit_dir) / first)
    check(len(sample) == points[-1], f"track 1's sample {first}: {len(sample)} frames (the SLICE frames {points[-1]})")
    worst = 0.0
    lags = set()
    tail_peak = 0.0
    rec_lags = []
    for t0, k, rec in exp:
        a0, a1 = points[k - 1], points[k]
        lag, g, res = match(main, sample[a0:a1], t0, int(0.015 * rr) if rec else 4)
        (rec_lags if rec else lags).append(lag) if rec else lags.add(lag)
        worst = max(worst, res if g > 0.05 else 9.0)
        start = t0 + (lag or 0)
        nxt = min([e - int(0.015 * rr) for e, _, _ in exp if e > t0] + [end])
        tail = main[start + (a1 - a0) + 2: min(nxt, start + (a1 - a0) + 2000)]
        tail_peak = max([tail_peak] + [abs(x) for x in tail])
    check(lags == {0}, f"each entered step plays its slice from its exact frame (best lags {sorted(lags)})")
    check(rec_lags and all(x is not None for x in rec_lags),
          f"each recorded step replays the slice it was recorded with (offsets {rec_lags} frames: its micro-timing)")
    check(worst <= 0.02, f"the rendered slices are the sample's slices (worst level-matched residual {worst:.4f})")
    tail_db = 20 * math.log10(tail_peak) if tail_peak > 0 else -200.0
    check(tail_db < -60.0, f"silence after each slice end (peak {tail_db:.1f} dBFS: the next slice is never played)")
    loads = [m2.kv(l) for l in log if l.startswith("LOAD ")]
    check(loads and int(loads[-1]["xruns"]) == 0, f"live engine: xruns {loads[-1]['xruns'] if loads else '?'}")
    print("slice check:", "OK" if ok else "FAILED")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("script")
    s.add_argument("--out", required=True)
    s.add_argument("--out-dir", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--log", required=True)
    v.add_argument("--render", required=True)
    v.add_argument("--kit-dir", required=True)
    v.add_argument("--kit-json", required=True)
    a = ap.parse_args()
    return script_cmd(a) if a.cmd == "script" else verify_cmd(a)


if __name__ == "__main__":
    sys.exit(main())
