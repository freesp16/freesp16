#!/usr/bin/env python3
"""SYNC-conversion cases for tests/unit/fx/test_fx_params.cpp (spec parameters.md "Test notes").

  tests/unit/fx/sync_cases.py            write tests/unit/fx/data/sync_convert.txt from the research model
  tests/unit/fx/sync_cases.py --check    regenerate in memory and compare (exit 77 without the research models)

Drives the MIT model tools/fx/sync_convert.py of the research checkout (through tools/golden-gen's import guard: only
tools/fx/*.py, never verify/) with the Ducker sixteenth tables replaced by Sixteen's own (FX-1210: T_A = 4(k/127)^2,
T_R = 0.25*128^(k/127), rounded to 0.001), for every family at 20, 60.5, 87.5, 120, 133.37 and 999 BPM, both
directions, every step of the grid being left. One line per (family, direction, bpm): the resulting step index j of
the grid being entered, run-length encoded "j*count" over the input steps lo..hi-1 (the C++ test expects
clamp01((j - lo') / (hi' - 1 - lo'))).
"""
import ctypes
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
sys.path.insert(0, str(ROOT / "tools" / "golden-gen"))
sys.dont_write_bytecode = True
from goldenlib import research  # noqa: E402

OUT = HERE / "data" / "sync_convert.txt"
BPMS = (20.0, 60.5, 87.5, 120.0, 133.37, 999.0)
FAMILIES = ("chorus", "flanger", "phaser", "insert_delay", "send_delay", "ducker_attack", "ducker_release")


def F(x):
    return ctypes.c_float(x).value


def spec_tables():
    ta = [F(round(4.0 * (k / 127.0) ** 2 * 1000.0) / 1000.0) for k in range(128)]
    tr = [F(round(0.25 * 128.0 ** (k / 127.0) * 1000.0) / 1000.0) for k in range(128)]
    return ta, tr


def generate(sc):
    ta, tr = spec_tables()
    sc.FAMILIES["ducker_attack"]["table"] = ta
    sc.FAMILIES["ducker_release"]["table"] = tr
    lines = ["# generated by tests/unit/fx/sync_cases.py from research tools/fx/sync_convert.py (MIT), FX-1210 tables"]
    for fam in FAMILIES:
        spec = sc.FAMILIES[fam]
        for to_sync in (1, 0):
            lo, hi = (spec["free"] if to_sync else spec["sync"])[1]
            for bpm in BPMS:
                T = sc.tempo_f32(bpm, insert=True)
                runs = []
                for i in range(lo, hi):
                    v = sc.norm_of(lo, hi, i)
                    if not fam.startswith("ducker"):
                        v = sc.clamp01_in(F(v))
                    _, d = sc.convert(fam, F(v), to_sync, T)
                    j = d["j"]
                    if runs and runs[-1][0] == j:
                        runs[-1][1] += 1
                    else:
                        runs.append([j, 1])
                lines.append("%s %d %r %s" % (fam, to_sync, bpm, " ".join("%d*%d" % (j, c) for j, c in runs)))
    return "\n".join(lines) + "\n"


def main():
    try:
        root = research.find_research(ROOT)
    except research.ResearchMissing as e:
        print("skipped:", e)
        return 77
    with research.Research(root) as r:
        text = generate(r.load("sync_convert"))
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != text:
            print("tests/unit/fx/data/sync_convert.txt is stale: run tests/unit/fx/sync_cases.py")
            return 1
        print("sync_convert.txt matches the research model")
        return 0
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
