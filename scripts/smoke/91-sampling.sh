# Sourced by scripts/host-smoke.sh (not run on its own): defines sampling_check <dir>, which runs its session in <dir>,
# prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch, $here, $tag,
# $p, $exe, $r (renderer), $code (launch's exit code).
#
# CHECK=sampling (in CHECK=all too) is the sampling check: one run of the app with the file device and a
# generated LINE IN stand-in (audio_input=file:in.wav, 16-bit stereo: 1 kHz at -12 dBFS on L, 1.5 kHz at -18 dBFS on R,
# looped), and three takes through the real sampler (engine capture ring -> Recorder thread -> Recordings/):
#   A  SOURCE LINE IN, REC LENGTH 2 BAR, track 3       `cmd sample-rec 3 2`   -> 176400 frames, stereo, L -12 / R -18 dBFS
#   B  SOURCE LINE IN L, REC LENGTH OFF, track 4        `cmd sample-rec 4 1` … `cmd sample-stop 4` ~1 s later -> mono,
#                                                       1 kHz at -12 dBFS, 0.8-1.4 s long
#   C  SOURCE RESAMPLE, REC LENGTH 1 BAR, track 5       -> 88200 frames, the master's 440 Hz test tone at -12 dBFS
# verify (inline python): three "SAMPLING TAKE ok" lines; each WAV is 24-bit PCM at 44.1 kHz with the expected channels
# and length, peaks within 0.5 dB and the dominant frequency within 2 % (zero crossings), no part files left, a
# `<take>.wav.json` sidecar with bpm 120 and bars 2 / 0 / 1; the last AUDIO line has xruns=0; exit code 0, STOP.
sampling_check() {
  dir=$1
  python3 - "$dir/in.wav" <<'PY'
import math, struct, sys, wave
rate, seconds = 44100, 2
w = wave.open(sys.argv[1], "wb")
w.setnchannels(2); w.setsampwidth(2); w.setframerate(rate)
a_l, a_r = 10 ** (-12 / 20), 10 ** (-18 / 20)
frames = bytearray()
for i in range(rate * seconds):  # whole periods of both tones: the loop is seamless
    l = a_l * math.sin(2 * math.pi * 1000 * i / rate)
    r = a_r * math.sin(2 * math.pi * 1500 * i / rate)
    frames += struct.pack("<hh", round(l * 32767), round(r * 32767))
w.writeframes(bytes(frames)); w.close()
PY
  cat > "$dir/script.txt" <<EOF
# generated by scripts/smoke/91-sampling.sh (time 0 = the app's first frame)
1000 cmd param sampling.length 0 2
1100 cmd sample-rec 3 2
5600 cmd sample-state
5700 cmd param sampling.source 0 1
5800 cmd param sampling.length 0 0
5900 cmd sample-rec 4 1
6900 cmd sample-stop 4
7400 cmd sample-state
7500 cmd param sampling.source 0 3
7600 cmd param sampling.length 0 1
7700 cmd sample-rec 5 2
10300 cmd sample-state
10600 quit
EOF
  launch "$dir" "$dir/script.txt" "$dir/log.txt" "${p}_AUDIO_INPUT=file:$dir/in.wav"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (PLATFORM|AUDIO|RUN|LOAD|FATAL|PARAM|STOP|CMD|SAMPLING)( |$)" \
    | sed "s/^.*$tag //" || true
  echo "--- verify"
  python3 - "$dir/log.txt" "$tag" > "$dir/verify.txt" 2>&1 <<'PY' || why="$why; sampling checks failed"
import json, math, os, re, struct, sys, wave
log, tag = sys.argv[1], sys.argv[2]
lines = [l.split(tag + " ", 1)[1].rstrip("\n") for l in open(log, errors="replace") if tag + " " in l]
takes = [l for l in lines if l.startswith("SAMPLING TAKE")]
fails = []
def check(ok, what):
    print(("  ok   " if ok else "  FAIL ") + what)
    if not ok:
        fails.append(what)
check(len(takes) == 3 and all(" ok " in t for t in takes), f"three takes finished ({len(takes)}: {[t[:40] for t in takes]})")
def read24(path):
    w = wave.open(path, "rb")
    ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    raw = w.readframes(n); w.close()
    chans = [[] for _ in range(ch)]
    for i in range(n):
        for c in range(ch):
            b = raw[(i * ch + c) * 3:(i * ch + c) * 3 + 3]
            chans[c].append(int.from_bytes(b, "little", signed=True) / 8388608.0)
    return ch, width, rate, n, chans
def dbfs(x):
    p = max(abs(v) for v in x) if x else 0.0
    return 20 * math.log10(p) if p > 0 else -999.0
def freq(x, rate):
    up = sum(1 for i in range(1, len(x)) if x[i - 1] < 0 <= x[i])
    return up * rate / len(x)
# name, channels, frames (exact, or a range), [(peak dBFS, Hz) per channel], sidecar bars
expect = [("A", 2, (176400, 176400), [(-12, 1000), (-18, 1500)], 2),
          ("B", 1, (int(0.8 * 44100), int(1.4 * 44100)), [(-12, 1000)], 0),
          ("C", 2, (88200, 88200), [(-12, 440), (-12, 440)], 1)]
for (name, ch_want, (lo, hi), levels, bars), t in zip(expect, takes):
    m = re.search(r"file=(\S+(?: \S+)*?\.wav) frames=(\d+)", t)
    if not m:
        check(False, f"take {name}: no file in '{t}'"); continue
    path = m.group(1)
    ch, width, rate, n, chans = read24(path)
    check(width == 3 and rate == 44100, f"take {name}: {os.path.basename(path)} is 24-bit at 44100 Hz ({8 * width}-bit, {rate} Hz)")
    check(ch == ch_want, f"take {name}: {ch} channel(s), want {ch_want}")
    check(lo <= n <= hi, f"take {name}: {n} frames, want {lo}..{hi}")
    for c, (db, hz) in enumerate(levels[:ch]):
        p, f = dbfs(chans[c]), freq(chans[c], rate)
        check(abs(p - db) <= 0.5, f"take {name} ch {c}: peak {p:.2f} dBFS, want {db} +/- 0.5")
        check(abs(f - hz) <= 0.02 * hz, f"take {name} ch {c}: {f:.1f} Hz, want {hz} +/- 2 %")
    side = path + ".json"
    ok = os.path.isfile(side)
    meta = json.load(open(side)) if ok else {}
    check(ok and abs(meta.get("bpm", 0) - 120) < 1e-6 and abs(meta.get("bars", -1) - bars) < 1e-6,
          f"take {name}: sidecar bpm={meta.get('bpm')} bars={meta.get('bars')}, want 120 / {bars}")
    folder = os.path.dirname(path)
    check(not any(f.endswith(".part") for f in os.listdir(folder)), f"take {name}: no part file left in Recordings/")
audio = [l for l in lines if l.startswith("AUDIO alsa_periods=")]
check(bool(audio) and " xruns=0 " in audio[-1] + " ", "last AUDIO line has xruns=0")
print("sampling checks:", "OK" if not fails else f"FAILED ({len(fails)})")
sys.exit(1 if fails else 0)
PY
  cat "$dir/verify.txt"
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
}
