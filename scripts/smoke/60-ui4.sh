# Sourced by scripts/host-smoke.sh (not run on its own): defines ui4_check <dir>, which runs its session(s) in
# <dir>, prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch,
# png_check, level_check, $here, $tag, $p, $exe, $r (renderer), $code (launch's exit code).
#
# CHECK=ui4 (in CHECK=all too) is the first screen walk: one run (no kit) whose script enters a FULL step on step
#   key 1 (HOME), opens TRACK MENU, LFO (screenshot), starts the transport (screenshot with the live dot), turns the rail
#   to SHAPE and pushes (the SHAPE popup, screenshot), stops, opens AMP ENVELOPE, PLAYBACK > SET SCALE, UTILITY and from
#   its first row (push) TOUCH STRIP SETTING (USER1) (screenshots), presses SCENE twice; `cmd open <id>` does the
#   jumps the panel has no key for (logged "UI OPEN <id> ok"). Checks: a NAV line per screen with its breadcrumb, no
#   refused open, every screenshot a PNG that decodes and is not one colour, the step lamp (LAMP step.1 lit) and
#   the SCENE key lamp (LAMP scene lit), exit code 0, STOP. The timing is the script's own (no waits on the host side).
# The first screen walk of one renderer (see the header): prints its lines, sets $why.
ui4_check() {
  dir=$1
  cat > "$dir/script.txt" <<EOF
# generated by scripts/host-smoke.sh (CHECK=ui4; time 0 = the app's first frame, ~ RUN)
1000 press step1
1100 release step1
1500 cmd open track.menu
2000 cmd open track.lfo
2500 screenshot $dir/lfo.png
2600 press play
3200 screenshot $dir/lfo-playing.png
3300 turn sel 1
3400 press sel.push
3900 screenshot $dir/lfo-shape.png
4000 press back
4100 press stop
4500 cmd open track.ampEnvelope
5000 screenshot $dir/amp-envelope.png
5500 cmd open track.playback
5600 cmd open track.playback.setScale
6100 screenshot $dir/set-scale.png
6500 cmd open utility
6700 press sel.push
7200 screenshot $dir/touch-strip.png
7300 press scene
7500 release scene
7800 press scene
8000 release scene
8600 quit
EOF
  launch "$dir" "$dir/script.txt" "$dir/log.txt" "${p}_LAMP_LOG=1"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (PLATFORM|RUN|FATAL|NAV|UI OPEN|STOP|CMD)( |$)" | sed "s/^.*$tag //" || true
  echo "--- verify"
  for s in "track.menu (HOME > TRACK MENU)" "track.lfo (HOME > TRACK MENU > LFO)" \
           "track.ampEnvelope (HOME > TRACK MENU > AMP ENVELOPE)" \
           "track.playback.setScale (HOME > TRACK MENU > PLAYBACK > SET SCALE)" "utility (HOME > UTILITY)" \
           "utility.touchStrip.user1 (HOME > UTILITY > TOUCH STRIP SETTING (USER1))"; do
    if grep -qF "$tag NAV $s" "$dir/log.txt"; then echo "  NAV $s: OK"
    else echo "  NAV $s: MISSING"; why="$why; no NAV ${s%% *}"; fi
  done
  if grep -F "$tag UI OPEN" "$dir/log.txt" | grep -qv " ok$"; then why="$why; an open was refused"; fi
  for shot in lfo lfo-playing lfo-shape amp-envelope set-scale touch-strip; do
    printf '  %s: ' "$shot"
    png_check "$dir/$shot.png" || why="$why; $shot.png blank or missing"
  done
  if grep -F "$tag LAMP" "$dir/log.txt" | grep -qE " step\.1=[0-9a-f]{6}/[1-9]"; then echo "  LAMP step.1 lit: OK"
  else echo "  LAMP step.1 lit: MISSING"; why="$why; no step lamp"; fi
  if grep -F "$tag LAMP" "$dir/log.txt" | grep -qE " scene=[0-9a-f]{6}/[1-9]"; then echo "  LAMP scene lit: OK"
  else echo "  LAMP scene lit: MISSING"; why="$why; no SCENE lamp"; fi
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
}
