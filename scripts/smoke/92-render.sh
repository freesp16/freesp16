# Sourced by scripts/host-smoke.sh (not run on its own): defines render_check <dir>, which runs its session in <dir>,
# prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch, $here, $tag, $p,
# $exe, $r (renderer), $code (launch's exit code).
#
# CHECK=render (in CHECK=all too) is the render check (REN-001…005, REN-010, REN-020/021/024 and the render CLI):
#   one run with the generated kit on tracks 1-16 of scene 1: pad 1 + the odd steps and pad 2 + the even steps
#   program pattern 1.1 (a 100 ms one-shot every 125 ms); stopped, SOURCE RESAMPLE, REC THRESHOLD PLAY, REC LENGTH
#   2 BAR, `cmd sample-rec 16 2` (standby: the take starts at the sequencer start edge); PLAY, then (the transport running, the RenderService on its own worker and Engine):
#     6.5 s  cmd render-job pattern repeats=128 bits=16             a 256 s render: the live output is muted meanwhile
#    12.0 s  cmd render-job pattern repeats=2 remainder=leave bits=24 the file the CLI is compared with
#    14.0 s  cmd render-job pattern repeats=64 + cmd render-cancel    cancelled: no file, the live output back
#    15.5 s  cmd render-job pattern totrack=1                         refused: no empty track (the kit fills 1-16)
#    16.0 s  cmd render-job pattern bars=1 totrack=1 into=16          render to track 16 (undoable LOAD)
#    18.0 s  cmd normalize <job 2's file> norm.wav -1, cmd analyze <job 2's file>; STOP; cmd save-as rendertest; quit
#   then, with the app gone, <name>_render_cli renders the saved bundle with job 2's options twice.
#   Checks: every job's start / done line (frames = 128 × 88200 for job 1; job 2 = 2 × 88200 + a tail ≤ 10 s, 24-bit
#   stereo WAV + sidecar bars 2 / bpm 120), the cancel and the refusal, "assigned … track=16 ok"; NORMALIZE changed=1
#   at ceiling 7476354; ANALYZE class=loop bars=2 bpm=120; MAIN (main.wav) silent (exact zeros) for ≥ 0.25 s from the
#   first job's start (REN-005 mute; the beat's own gaps are 25 ms, checked < 0.1 s) and sounding again after it; the CLI's hash
#   equal in both runs and equal to job 2's in-app hash (the same render core over the saved project); REN-007: the
#   RESAMPLE take (2 bars, recorded while job 1 muted the live output: the resample tap is not muted) equals job 2's
#   first 2 bars within -100 dBFS after aligning the first onsets (both 24-bit; the lag is printed); xruns 0.
#   Timings are relative to the desktop (the render runs ≈ 50-100x real time here); the device budget is
#   bench_render_offline's.
render_check() {
  dir=$1
  data="$dir/data"
  python3 "$here/tools/gen-test-kit.py" --data-dir "$data" --json "$dir/kit.json" > "$dir/gen-test-kit.txt"
  job2="$data/RenderedAudio/Untitled_1_1_2.wav"
  python3 - "$dir/script.txt" "$job2" "$dir/norm.wav" <<'PY'
import sys
out, job2, norm = sys.argv[1:4]
ev, t = [], 2500
def at(ms, line): ev.append((ms, line))
def key(name, gap=90):
    global t
    at(t, f"press {name}"); at(t + 40, f"release {name}"); t += gap
key("pad1", 200)
for s in range(1, 17, 2): key(f"step{s}")
key("pad2", 200)
for s in range(2, 17, 2): key(f"step{s}")
at(3700, "cmd param sampling.source 0 3")     # RESAMPLE
at(3750, "cmd param sampling.threshold 0 42")  # PLAY: starts with the transport
at(3800, "cmd param sampling.length 0 2")      # 2 BAR
at(3900, "cmd sample-rec 16 2")
at(4200, "press play"); at(4240, "release play")
at(6500, "cmd render-job pattern repeats=128 bits=16")
at(12000, "cmd render-job pattern repeats=2 remainder=leave bits=24")
at(14000, "cmd render-job pattern repeats=64")
at(14010, "cmd render-cancel")
at(15500, "cmd render-job pattern totrack=1")
at(16000, "cmd render-job pattern bars=1 totrack=1 into=16")
at(18000, f"cmd normalize {job2} {norm} -1")
at(18200, f"cmd analyze {job2}")
at(18500, "press stop"); at(18540, "release stop")
at(19000, "cmd save-as rendertest")
at(23000, "quit")
with open(out, "w") as f:
    f.write("# generated by scripts/smoke/92-render.sh (time 0 = the app's first frame)\n")
    for ms, line in sorted(ev, key=lambda e: e[0]):
        f.write(f"{ms} {line}\n")
PY
  launch "$dir" "$dir/script.txt" "$dir/log.txt" "${p}_DEV_KIT=Samples/TestKit"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (PLATFORM|AUDIO|RUN|LOAD|KIT|FATAL|RENDER|NORMALIZE|ANALYZE|SAMPLING|SAVED|STOP|CMD unknown)( |$)" \
    | sed "s/^.*$tag //" || true
  cli="${exe}_render_cli"
  bundle="$data/Projects/rendertest.sixteen"
  if [ -x "$cli" ] && [ -d "$bundle" ]; then
    "$cli" --project "$bundle" --library "$data" --repeats 2 --remainder leave --bits 24 --out "$dir/cli.wav" \
      > "$dir/cli1.txt" 2>&1 || why="$why; render CLI run 1 failed"
    "$cli" --project "$bundle" --library "$data" --repeats 2 --remainder leave --bits 24 --no-write \
      > "$dir/cli2.txt" 2>&1 || why="$why; render CLI run 2 failed"
    echo "--- render CLI"
    cat "$dir/cli1.txt" "$dir/cli2.txt"
  else
    why="$why; no render CLI ($cli) or no saved bundle ($bundle)"
  fi
  echo "--- verify"
  python3 - "$dir" "$tag" > "$dir/verify.txt" 2>&1 <<'PY' || why="$why; render checks failed"
import json, os, re, struct, sys
d, tag = sys.argv[1], sys.argv[2]
ok = True
def check(cond, text):
    global ok
    print(("PASS " if cond else "FAIL ") + text)
    ok = ok and bool(cond)
lines = [l.split(tag + " ", 1)[1].rstrip("\n") for l in open(os.path.join(d, "log.txt"), errors="replace") if tag + " " in l]
def kv(line):
    return dict(m.groups() for m in re.finditer(r"(\w+)=(\S+)", line))
starts = [kv(l) for l in lines if l.startswith("RENDER JOB start")]
dones = [l for l in lines if l.startswith("RENDER JOB done") or l.startswith("RENDER JOB failed")]
check(len(starts) == 4, f"RENDER JOB start lines: {len(starts)}, expected 4 (jobs 1, 2, the cancelled one, into=16)")
check(len(dones) == 5, f"RENDER JOB done/failed lines: {len(dones)}, expected 5 (+ the refusal)")
done = [kv(l) for l in dones]
if len(done) == 5:
    check(done[0].get("cancelled") == "0" and done[0].get("frames") == str(128 * 88200), f"job 1 (128 repeats): {dones[0]}")
    f2 = int(done[1].get("frames", 0))
    check(done[1].get("cancelled") == "0" and 2 * 88200 <= f2 <= 2 * 88200 + 10 * 44100, f"job 2 (2 repeats + tail): frames {f2}")
    check(done[1].get("bars") == "2.000" and done[1].get("bpm") == "120.000", f"job 2 bars / bpm: {done[1].get('bars')} / {done[1].get('bpm')}")
    check(dones[2] == "RENDER JOB done cancelled=1", f"the cancelled job: {dones[2]}")
    check("No empty track" in dones[3], f"render to track without an empty track refused: {dones[3]}")
    check(done[4].get("into") == "16", f"render to track 16: {dones[4]}")
    job2 = done[1].get("file", "")
    try:
        with open(job2, "rb") as w:
            h = w.read(64)
        fmt_ok = h[:4] == b"RIFF" and h[8:12] == b"WAVE" and struct.unpack("<H", h[22:24])[0] == 2 and struct.unpack("<H", h[34:36])[0] == 24
        check(fmt_ok, f"job 2's file is a 24-bit stereo WAV: {os.path.basename(job2)}")
        side = json.load(open(job2 + ".json"))
        check(side.get("bars") == 2 and abs(side.get("bpm", 0) - 120) < 1e-6, f"sidecar bars / bpm: {side.get('bars')} / {side.get('bpm')}")
    except OSError as e:
        check(False, f"job 2's file: {e}")
    names = sorted(os.listdir(os.path.dirname(job2))) if job2 else []
    check([n for n in names if n.endswith(".wav")] == ["Untitled_1_1_1.wav", "Untitled_1_1_2.wav", "Untitled_1_1_3.wav"],
          f"RenderedAudio holds jobs 1, 2 and the into=16 one, nothing of the cancelled job: {names}")
check(any(l.startswith("RENDER JOB assigned scene=1 track=16 ok") for l in lines), "render to track: assigned to track 16 (undoable LOAD)")
norm = [l for l in lines if l.startswith("NORMALIZE")]
check(norm and "changed=1" in norm[0] and "ceiling=7476354" in norm[0] and "after=7476354" in norm[0], f"normalize: {norm[:1]}")
an = [l for l in lines if l.startswith("ANALYZE")]
check(an and "class=loop" in an[0] and "bars=2.000" in an[0] and "bpm=120.000" in an[0], f"analyze: {an[:1]}")
# REN-005: MAIN silent while job 1 renders, sounding before and after.
with open(os.path.join(d, "main.wav"), "rb") as f:
    data = f.read()
pos, rate, chans, pcm = 12, 44100, 2, b""
while pos + 8 <= len(data):
    cid, n = data[pos:pos + 4], struct.unpack("<I", data[pos + 4:pos + 8])[0]
    if cid == b"fmt ":
        chans, rate = struct.unpack("<HI", data[pos + 10:pos + 16])
    if cid == b"data":
        pcm = data[pos + 8:pos + 8 + n]
        break
    pos += 8 + n + (n & 1)
frames = len(pcm) // (2 * chans)
samples = struct.unpack("<%dh" % (frames * chans), pcm[:frames * chans * 2])
def longest_zero(a, b):
    best = run = 0
    best_at = a
    for i in range(max(0, int(a * rate)), min(frames, int(b * rate))):
        if samples[i * chans] == 0 and samples[i * chans + 1] == 0:
            run += 1
            if run > best:
                best, best_at = run, i - run + 1
        else:
            run = 0
    return best / rate, best_at / rate
before, _ = longest_zero(4.6, 6.4)
mute, mute_at = longest_zero(6.4, 11.5)
check(before < 0.1, f"the beat plays before the render: longest silence {before:.3f} s in 4.6-6.4 s")
check(mute >= 0.25 and 6.4 <= mute_at <= 7.5, f"live output muted during job 1: {mute:.3f} s of exact silence from {mute_at:.3f} s")
after, _ = longest_zero(mute_at + mute + 0.2, mute_at + mute + 2.2)
check(after < 0.1, f"the live output is back after job 1: longest silence {after:.3f} s in the next 2 s")
# The render CLI over the saved project = job 2 in the app.
def cli_hash(name):
    try:
        for l in open(os.path.join(d, name)):
            if l.startswith("RENDER "):
                return kv(l).get("hash")
    except OSError:
        return None
h1, h2 = cli_hash("cli1.txt"), cli_hash("cli2.txt")
check(h1 is not None and h1 == h2, f"render CLI: the same hash in both runs ({h1} / {h2})")
check(len(done) == 5 and h1 == done[1].get("hash"), f"render CLI hash = job 2's in-app hash ({h1} / {done[1].get('hash') if len(done) == 5 else '-'})")
# REN-007: the live RESAMPLE take vs the offline render of the same pattern (job 2), after alignment.
def wav24(path):
    raw = open(path, "rb").read()
    pos, ch, bits, body = 12, 2, 0, b""
    while pos + 8 <= len(raw):
        cid, n = raw[pos:pos + 4], struct.unpack("<I", raw[pos + 4:pos + 8])[0]
        if cid == b"fmt ":
            ch, bits = struct.unpack("<H", raw[pos + 10:pos + 12])[0], struct.unpack("<H", raw[pos + 22:pos + 24])[0]
        if cid == b"data":
            body = raw[pos + 8:pos + 8 + n]
            break
        pos += 8 + n + (n & 1)
    assert bits == 24, f"{path}: {bits}-bit"
    vals = [int.from_bytes(body[i:i + 3], "little", signed=True) / 8388608.0 for i in range(0, len(body) - 2, 3)]
    return [vals[c::ch] for c in range(ch)]
take = []
for l in lines:
    if l.startswith("SAMPLING TAKE ok"):
        t = kv(l)
        t["file"] = re.search(r"file=(.*?) frames=", l).group(1)  # "Recordings/REC 001.wav": a space in the name
        take.append(t)
check(len(take) == 1 and take[0].get("frames") == "176400" and take[0].get("channels") == "2",
      f"RESAMPLE take: {take[0] if take else 'none'}")
if take and len(done) == 5:
    a, b = wav24(take[0]["file"]), wav24(done[1]["file"])
    onset = lambda x: next((i for i, v in enumerate(x) if abs(v) > 1e-3), -1)
    lag = onset(a[0]) - onset(b[0])
    n = min(len(a[0]) - max(lag, 0), 176400 - max(-lag, 0))
    diff = max(abs(a[c][i + max(lag, 0)] - b[c][i + max(-lag, 0)]) for c in (0, 1) for i in range(n))
    import math
    db = 20 * math.log10(diff) if diff > 0 else -999
    check(n > 170000 and db <= -100, f"REN-007: RESAMPLE take = offline render within {db:.1f} dBFS (lag {lag} frames, {n} frames compared)")
loads = [kv(l) for l in lines if l.startswith("LOAD ")]
audio = [kv(l) for l in lines if l.startswith("AUDIO ")]
xr = [x.get("xruns") for x in loads[-1:] + audio[-1:]]
check(all(v == "0" for v in xr) and xr, f"xruns 0 (LOAD, AUDIO): {xr}")
sys.exit(0 if ok else 1)
PY
  cat "$dir/verify.txt"
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
}
