# Sourced by scripts/host-smoke.sh (not run on its own): defines settings_check <dir>, which runs its sessions in
# <dir>, prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch,
# png_check, $here, $tag, $p, $r (renderer), $code (launch's exit code).
#
# CHECK=settings (in CHECK=all too) is the settings check ("a changed value survives a restart";
#   SET-010, UI-325): three runs on one data directory.
#   run 1  SHIFT + HOME opens UTILITY (panel keys only from there): the rotary to the end of the list (DISK SPACE), 12
#          rows up = RESUME (push, turn to OFF, push), 7 down = STRIP ACTS ON (→ SELECTED TRACK), 4 up = UI SCALE (→
#          125 %); `cmd open utility.audioDevice` (the jump the smoke needs; the panel path is checked by the unit and
#          snapshot tests), 5 rows down = INPUT LATENCY (+7); a screenshot of UTILITY; `cmd save-as settings-smoke` (so
#          RESUME has a project to skip); `cmd prefs`; quit. Checks: preferences.json is schema 1 and holds the four
#          values, the save was written within 1 s of the last edit (PREFS writes ≥ 1 before the quit's flush), STOP.
#   run 2  a restart: "PREFS loaded … values=n" with the four values (`cmd prefs`), RESUME OFF in effect ("PROJECT new"
#          although a project was saved), UTILITY reached again by SHIFT + HOME.
#   run 3  kill -9 during saves: the script sets a preference and flushes 120 times (`cmd pref`, `cmd prefs-flush`,
#          25 ms apart); the app is killed (SIGKILL) in the middle. Check: preferences.json still parses, no
#          preferences.json.corrupt (the atomic temp → fsync → rename write, services/store/AtomicWriter).
# Artefacts: log.txt (run 1), log2.txt, log3.txt, run1.txt … run3.txt, utility.png, preferences.json.
settings_check() {
  dir=$1
  cat > "$dir/run1.txt" <<EOF
# generated by scripts/smoke/97-settings.sh (run 1; time 0 = the app's first frame)
1500 press shift
1550 press home
1600 release home
1650 release shift
2000 turn sel 200
2100 turn sel -12
2200 press sel.push
2300 turn sel -1
2400 press sel.push
2500 turn sel 7
2600 press sel.push
2700 turn sel 1
2800 press sel.push
2900 turn sel -4
3000 press sel.push
3100 turn sel 1
3200 press sel.push
3500 screenshot $dir/utility.png
3700 cmd open utility.audioDevice
3900 turn sel 5
4000 press sel.push
4100 turn sel 7
4200 press sel.push
4300 press back
4600 cmd save-as settings-smoke
5800 cmd prefs
6200 quit
EOF
  launch "$dir" "$dir/run1.txt" "$dir/log.txt"
  [ "$code" = 0 ] || why="$why; run 1 exit code $code"
  cp "$dir/data/preferences.json" "$dir/preferences.json" 2>/dev/null || true
  cat > "$dir/run2.txt" <<EOF
# generated by scripts/smoke/97-settings.sh (run 2: the restart)
1500 cmd prefs
1800 press shift
1850 press home
1900 release home
1950 release shift
2500 quit
EOF
  launch "$dir" "$dir/run2.txt" "$dir/log2.txt"
  [ "$code" = 0 ] || why="$why; run 2 exit code $code"
  {
    echo "# generated by scripts/smoke/97-settings.sh (run 3: kill -9 during saves)"
    i=0
    while [ $i -lt 120 ]; do
      t=$((1500 + i * 25))
      echo "$t cmd pref transport.metronomeVolume $((i % 128))"
      echo "$((t + 10)) cmd prefs-flush"
      i=$((i + 1))
    done
    echo "8000 quit"
  } > "$dir/run3.txt"
  BACKGROUND=1 launch "$dir" "$dir/run3.txt" "$dir/log3.txt"
  bg=$!
  waited=0
  while [ $waited -lt 600 ] && kill -0 $bg 2>/dev/null; do
    n=$(grep -cF "$tag PREFS flushed" "$dir/log3.txt" 2>/dev/null) || true
    [ "${n:-0}" -ge 30 ] && break
    sleep 0.05; waited=$((waited + 1))
  done
  pid=$(grep -F "$tag START " "$dir/log3.txt" | sed -n 's/.* pid=\([0-9]*\).*/\1/p' | head -1)
  if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
    kill -KILL "$pid"
    echo "--- run 3: killed pid $pid (SIGKILL) after $(grep -cF "$tag PREFS flushed" "$dir/log3.txt") saves"
  else
    why="$why; run 3 ended before the kill"
  fi
  wait $bg 2>/dev/null || true
  for f in log log2 log3; do
    echo "--- $f"
    grep -F "$tag " "$dir/$f.txt" | grep -E " (PLATFORM|RUN|FATAL|NAV|PROJECT|SAVED|PREFS|STOP|CMD unknown)( |$)" \
      | grep -v "PREFS set \|PREFS flushed writes" | sed "s/^.*$tag //" || true
  done
  echo "--- verify"
  python3 - "$dir" "$tag" > "$dir/verify.txt" 2>&1 <<'PY' || why="$why; settings checks failed"
import json, os, re, sys
d, tag = sys.argv[1], sys.argv[2]
failed = []
def check(ok, text):
    print(f"  {text}: {'OK' if ok else 'FAILED'}")
    if not ok:
        failed.append(text)
def lines(name):
    try:
        return [l.split(tag + " ", 1)[1].rstrip("\n") for l in open(os.path.join(d, name), errors="replace") if tag + " " in l]
    except OSError:
        return []
want = {"project.resume": 0, "ribbon.applyTo": 1, "ui.scale": 125, "audio.inputLatency": 7}
try:
    p = json.load(open(os.path.join(d, "preferences.json")))
except (OSError, ValueError) as e:
    p = {}
    print(f"  preferences.json after run 1: {e}")
check(p.get("version") == 1 and str(p.get("format", "")).endswith("-preferences"), "run 1: preferences.json schema 1")
vals = p.get("values", {})
for k, v in want.items():
    check(vals.get(k) == v, f"run 1: preferences.json {k} = {v} (found {vals.get(k)})")
l1 = lines("log.txt")
check(any(l.startswith("NAV utility ") for l in l1), "run 1: SHIFT + HOME opened UTILITY")
check(any(l.startswith("SAVED settings-smoke ok") for l in l1), "run 1: project saved")
w = [int(m.group(1)) for l in l1 for m in [re.match(r"PREFS file=.* writes=(\d+)", l)] if m]
check(bool(w) and w[-1] >= 1, f"run 1: the debounced save ran before the quit (writes={w[-1] if w else None})")
check(any(l.startswith("STOP") for l in l1), "run 1: STOP")
l2 = lines("log2.txt")
loaded = [l for l in l2 if l.startswith("PREFS loaded")]
check(bool(loaded), "run 2: PREFS loaded")
pv = next((l for l in l2 if l.startswith("PREFS ") and "project.resume=" in l), "")
for k, v in want.items():
    check(f" {k}={v}" in pv, f"run 2: {k}={v} after the restart")
check(any(l.startswith("PROJECT new") for l in l2), "run 2: RESUME OFF in effect (PROJECT new)")
check(any(l.startswith("NAV utility ") for l in l2), "run 2: UTILITY again")
check(any(l.startswith("STOP") for l in l2), "run 2: STOP")
try:
    p3 = json.load(open(os.path.join(d, "data", "preferences.json")))
    ok3 = p3.get("version") == 1 and "transport.metronomeVolume" in p3.get("values", {})
except (OSError, ValueError) as e:
    ok3 = False
    print(f"  run 3: {e}")
check(ok3, "run 3: preferences.json valid after kill -9 during saves")
check(not os.path.exists(os.path.join(d, "data", "preferences.json.corrupt")), "run 3: nothing moved aside")
print(f"=== settings {'PASS' if not failed else 'FAIL'} ({len(failed)} failed)")
sys.exit(1 if failed else 0)
PY
  cat "$dir/verify.txt"
  printf '  utility.png: '
  png_check "$dir/utility.png" || why="$why; utility.png blank or missing"
  first="$dir/log.txt"
}
