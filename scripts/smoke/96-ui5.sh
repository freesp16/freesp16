# Sourced by scripts/host-smoke.sh (not run on its own): defines ui5_check <dir>, which runs its session(s) in <dir>,
# prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch, png_check,
# $here, $tag, $p, $exe, $r (renderer), $code (launch's exit code).
#
# CHECK=ui5 (in CHECK=all too) is the second screen walk: one run (no kit) whose script opens ARRANGER and pushes
# (a row with the current scene/pattern before END OF ARRANGEMENT), MIXER › OUTPUT SETTING, TRACK MENU › SAMPLING/EDIT,
# presses REC twice (standby → recording at once with THRESHOLD OFF → stop: a take of the silent input becomes the
# track's RECORDED TEMP.), BACK (the unsaved-take question) and DISCARD, LIVE SAMPLING, MIDI NOTE, MIDI CC1 and
# PROJECT › RENDER AUDIO, whose RENDER renders the pattern; a screenshot per screen. `cmd open <id>` does the jumps the
# panel has no key for (logged "UI OPEN <id> ok"). Checks: a NAV line per screen with its breadcrumb, no refused open,
# every screenshot a PNG that decodes and is not one colour, the screen's REC reached the sampler ("SAMPLING REC …
# (screen)"), the take was assigned and discarded, the render finished ("RENDER UI done files=1"), exit code 0, STOP.
# The second screen walk of one renderer (see the header): prints its lines, sets $why.
ui5_check() {
  dir=$1
  cat > "$dir/script.txt" <<EOF
# generated by scripts/smoke/96-ui5.sh (CHECK=ui5; time 0 = the app's first frame, ~ RUN)
1000 cmd open arranger
1300 press sel.push
1400 release sel.push
1800 screenshot $dir/arranger.png
2000 cmd open mixer
2200 cmd open mixer.output
2700 screenshot $dir/output.png
2900 cmd open track.menu
3100 cmd open sampling.edit
3600 screenshot $dir/sampling-edit.png
3700 press rec
3800 release rec
4600 screenshot $dir/sampling-recording.png
4700 press rec
4800 release rec
6000 press back
6100 release back
6400 turn sel 1
6500 press sel.push
6600 release sel.push
7000 cmd open sampling.live
7500 screenshot $dir/live-sampling.png
7700 cmd open track.note
8200 screenshot $dir/midi-note.png
8400 cmd open track.cc1
8900 screenshot $dir/midi-cc1.png
9100 cmd open project
9300 cmd open project.renderAudio
9500 turn sel 23
9600 press sel.push
9700 release sel.push
10200 screenshot $dir/render-progress.png
14000 screenshot $dir/render.png
14500 quit
EOF
  launch "$dir" "$dir/script.txt" "$dir/log.txt"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (PLATFORM|RUN|FATAL|NAV|UI OPEN|STOP|SAMPLING|RENDER)( |$)" \
    | sed "s/^.*$tag //" || true
  echo "--- verify"
  for s in "arranger (HOME > ARRANGER)" "mixer.output (HOME > MIXER > OUTPUT SETTING)" \
           "sampling.edit (HOME > TRACK MENU > SAMPLING/EDIT)" "sampling.live (HOME > TRACK MENU > LIVE SAMPLING)" \
           "track.note (HOME > TRACK MENU > MIDI NOTE)" "track.cc1 (HOME > TRACK MENU > MIDI CC1)" \
           "project.renderAudio (HOME > PROJECT > RENDER AUDIO)"; do
    if grep -qF "$tag NAV $s" "$dir/log.txt"; then echo "  NAV $s: OK"
    else echo "  NAV $s: MISSING"; why="$why; no NAV ${s%% *}"; fi
  done
  if grep -F "$tag UI OPEN" "$dir/log.txt" | grep -qv " ok$"; then why="$why; an open was refused"; fi
  for shot in arranger output sampling-edit sampling-recording live-sampling midi-note midi-cc1 render; do
    printf '  %s: ' "$shot"
    png_check "$dir/$shot.png" || why="$why; $shot.png blank or missing"
  done
  for want in "SAMPLING REC track=1 .*(screen)" "SAMPLING ASSIGN scene=1 track=1" \
              "RENDER UI done files=1 cancelled=0 failed=0"; do
    if grep -F "$tag " "$dir/log.txt" | grep -qE "$want"; then echo "  $want: OK"
    else echo "  $want: MISSING"; why="$why; no '$want'"; fi
  done
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
}
