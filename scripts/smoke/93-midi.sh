# Sourced by scripts/host-smoke.sh (not run on its own): defines midi_check <dir>, which runs its session in <dir>,
# prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch, $here, $tag,
# $p, $exe, $r (renderer), $code (launch's exit code).
#
# CHECK=midi (in CHECK=all too) is the MIDI check, on the scripted virtual MIDI port (io/midi/VirtualPort.h;
# midi_providers=virtual, from the run's settings file, keeps the desktop's own MIDI devices out of it):
#   session  the virtual input plays a 120.0 BPM clock with +/-1 ms random jitter from 2 s, MIDI Start at 2.5 s, a
#            few notes and CC 7 = 80 on channel 1; the input script turns on SYNC SOURCE = MIDI CLOCK, IN clock +
#            start/stop, OUT clock + start/stop (`cmd param`, 0.2 s), quits at 11.5 s; the virtual output records
#            every message it was sent
#   checks   "MIDI ok" at start; the last "MIDI stats" line: followed tempo 120.0 (the display hysteresis, SYN-012),
#            > 300 messages in, clock ticks out, no late or dropped message, clock-out jitter p99 reported (gated at
#            0.5 ms here too: the desktop's SCHED_FIFO sender; the device number is the unit's); the recorded output:
#            a Start (FA) and the clock's mean tick interval = 120.0 +/- 0.1 BPM; "MIDI MODEL track.volume scope=0
#            value=80" (the CC reached the model, non-undoable); xruns 0 in the AUDIO and LOAD lines; STOP; exit 0.
#            Prints the MIDI / AUDIO / LOAD lines and the analysis.
# The followed transport's phase against the clock (<= 1 sample per bar), the 160.0 BPM display and the jitter of the
# stamps under callback jitter are unit tests (tests/unit/midi, ctest -L midi); this check is the live path: port
# thread → hub → engine → transport → clock out → sender → port, in the real app.
midi_check() {
  dir=$1
  cat > "$dir/midi.txt" <<EOF
# generated by scripts/smoke/93-midi.sh: virtual MIDI input (ms since the port opened)
2000 clock 120 8.4 1.0
2490 start
4000 90 00 64
4100 80 00 00
5000 B0 07 50
EOF
  cat > "$dir/script.txt" <<EOF
# generated by scripts/smoke/93-midi.sh (time 0 = the app's first frame, ~ RUN)
200 cmd param midi.syncSource 0 1
200 cmd param midi.in.clock 0 1
200 cmd param midi.in.startStop 0 1
200 cmd param midi.out.clock 0 1
200 cmd param midi.out.startStop 0 1
11500 quit
EOF
  # midi_providers from the settings file (the app settings → io::midi::configure), the rest from the environment.
  mkdir -p "$dir/config/$PROJECT_NAME"
  echo "midi_providers=virtual" > "$dir/config/$PROJECT_NAME/$PROJECT_NAME.conf"
  launch "$dir" "$dir/script.txt" "$dir/log.txt" "${p}_MIDI_VIRTUAL=$dir/midi.txt" \
    "${p}_MIDI_VIRTUAL_OUT=$dir/midi-out.txt"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (MIDI|AUDIO|RUN|LOAD|FATAL|STOP)( |$)" | sed "s/^.*$tag //" || true
  grep -qF "$tag MIDI ok" "$dir/log.txt" || why="$why; no MIDI ok"
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
  echo "--- verify"
  python3 - "$dir/log.txt" "$dir/midi-out.txt" "$tag" > "$dir/verify.txt" 2>&1 <<'PY' || why="$why; midi checks failed"
import re, sys
log, out, tag = sys.argv[1], sys.argv[2], sys.argv[3]
lines = [l.split(tag + " ", 1)[1].strip() for l in open(log, errors="replace") if tag + " " in l]
ok = True
def check(cond, text):
    global ok
    print(("  OK    " if cond else "  FAIL  ") + text)
    ok = ok and cond
stats = [l for l in lines if l.startswith("MIDI stats ")]
check(bool(stats), "a MIDI stats line")
if stats:
    kv = dict(re.findall(r"(\w+)=([-\d.]+)", stats[-1]))
    num = lambda k: float(kv.get(k, "nan"))
    check(abs(num("tempo") - 120.0) < 1e-6, f"followed tempo shown {kv.get('tempo')} (want 120.0)")
    check(num("in") > 300, f"messages in {kv.get('in')} (> 300)")
    check(num("clocks") > 300, f"clock ticks out {kv.get('clocks')} (> 300)")
    check(num("late") == 0 and num("dropped") == 0, f"late {kv.get('late')} dropped {kv.get('dropped')} (0)")
    check(num("jitter_p99") <= 500, f"clock-out jitter p99 {kv.get('jitter_p99')} us, max {kv.get('jitter_max')} us "
          f"(<= 500 us; host)")
for l in lines:
    if l.startswith(("AUDIO alsa_periods", "LOAD ")):
        m = re.search(r"xruns=(\d+)", l)
        if m:
            check(m.group(1) == "0", "xruns 0: " + l[:60])
try:
    recs = [l.split() for l in open(out)]
except OSError as e:
    recs = []
    check(False, f"recorded output: {e}")
starts = [int(r[0]) for r in recs if len(r) > 1 and r[1] == "FA"]
ticks = [int(r[0]) for r in recs if len(r) > 1 and r[1] == "F8"]
check(bool(starts), f"Start (FA) sent: {len(starts)}")
model = [l for l in lines if l.startswith("MIDI MODEL ")]
check(any(l.startswith("MIDI MODEL track.volume scope=0 value=80") for l in model),
      "CC 7 = 80 on channel 1 wrote the model (non-undoable): " + (model[0] if model else "no MIDI MODEL line"))
check(not any("in: 1=VIRTUAL" in l and "2=" in l for l in lines if l.startswith("MIDI ok")),
      "only the virtual port (midi_providers=virtual from the settings file)")
if len(ticks) > 50:
    # The mean interval after the first beat (single intervals alternate 918 / 919 frames: the stamps are whole
    # samples, 918.75 frames per tick at 120 BPM / 44.1 kHz).
    iv = [(b - a) / 1e6 for a, b in zip(ticks[24:], ticks[25:])]
    mean = (ticks[-1] - ticks[24]) / 1e6 / (len(ticks) - 25)
    bpm = 60000.0 / (24.0 * mean)
    check(abs(bpm - 120.0) <= 0.1, f"clock out: {len(ticks)} ticks, mean interval {mean:.4f} ms = {bpm:.3f} BPM "
          f"(120.0 +/- 0.1), single intervals p1..p99 {sorted(iv)[len(iv)//100]:.3f}..{sorted(iv)[-len(iv)//100-1]:.3f} ms")
else:
    check(False, f"clock out: only {len(ticks)} ticks recorded")
sys.exit(0 if ok else 1)
PY
  cat "$dir/verify.txt"
}
