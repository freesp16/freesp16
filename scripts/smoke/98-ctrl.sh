# Sourced by scripts/host-smoke.sh (not run on its own): defines ctrl_check <dir>, which runs its session in <dir>,
# prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch, $here, $tag,
# $p, $exe, $r (renderer), $code (launch's exit code).
#
# CHECK=ctrl (in CHECK=all too) is the controller check: a virtual MIDI pad controller (the scripted virtual port of
# io/midi/VirtualPort.h, midi_providers=virtual) marked as a controller with the setting controllers=VIRTUAL — it runs
# the built-in Generic 16 + 8 profile (UI-131) — plays the generated test kit (tools/gen-test-kit.py, dev_kit):
#   session  notes 36-51 on channel 10 (pads 1-16), velocity 110, 250 ms apart from 3000 ms (port time), each
#            released 120 ms later; then CC 70 (enc.1) +3 / -3 detents in two's complement, MMC stop, a note 60 on
#            channel 1 (not bound: it must stay MIDI input); the virtual output records the profile's lamp messages;
#            the input script expands the virtual panel (virtual_panel=expanded), taps its pad 1 at 9.5 s
#            (the drawer's pad 1 = canvas 192..284 x 580..628 = window point 150, 375), screenshot, quits at 11 s
#   checks   "CONTROLLERS ok" and "CTRL port 1 VIRTUAL controller profile=generic-16-8"; the last "CTRL stats" line:
#            consumed >= 34 (the 32 pad notes, CC 70, MMC), triggers = 16 (every pad hit went straight to the engine,
#            UI-118), lamps > 0, dropped 0; tools/analyze-wav.py --kit on MAIN 2.5-7.5 s: the 16 pads' samples in pad
#            order, 250 +/- 40 ms apart (the pad notes reached the engine and played); the unbound note 60 on channel 1
#            sounds at ~7.6 s through the MIDI input (track 1, not consumed, UI-136); the panel tap sounds at ~9.5 s; the recorded output holds pad lamp note-ons
#            (99 24..33, the lamps echoed) with a non-zero colour; the screenshot decodes; xruns 0; STOP; exit 0.
ctrl_check() {
  dir=$1
  python3 "$here/tools/gen-test-kit.py" --data-dir "$dir/data" --json "$dir/kit.json" > "$dir/gen-test-kit.txt"
  python3 - "$dir/midi.txt" <<'PY'
import sys
lines = ["# generated by scripts/smoke/98-ctrl.sh: a Generic 16 + 8 controller on the virtual port (ms since it opened)"]
t = 3000
for n in range(16):
    lines.append(f"{t} 99 {36 + n:02X} 6E")
    lines.append(f"{t + 120} 89 {36 + n:02X} 00")
    t += 250
lines += [f"{t + 300} B9 46 01", f"{t + 350} B9 46 02", f"{t + 400} B9 46 7D",
          f"{t + 600} 90 3C 64", f"{t + 700} 80 3C 00"]
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
PY
  # MMC stop as raw bytes cannot be written with the 3-byte script steps; the profile's CC 116 (stop) stands in.
  echo "8500 B9 74 7F" >> "$dir/midi.txt"
  echo "8550 B9 74 00" >> "$dir/midi.txt"
  cat > "$dir/script.txt" <<EOF
# generated by scripts/smoke/98-ctrl.sh (time 0 = the app's first frame, ~ RUN)
9500 tap 150 375
10000 screenshot $dir/panel.png
11000 quit
EOF
  mkdir -p "$dir/config/$PROJECT_NAME"
  echo "midi_providers=virtual" > "$dir/config/$PROJECT_NAME/$PROJECT_NAME.conf"
  launch "$dir" "$dir/script.txt" "$dir/log.txt" "${p}_MIDI_VIRTUAL=$dir/midi.txt" \
    "${p}_MIDI_VIRTUAL_OUT=$dir/midi-out.txt" "${p}_CONTROLLERS=VIRTUAL" "${p}_VIRTUAL_PANEL=expanded" \
    "${p}_DEV_KIT=Samples/TestKit"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (CTRL|CONTROLLERS|VIRTUAL-PANEL|MIDI|AUDIO|RUN|LOAD|KIT|FATAL|STOP)( |$)" \
    | sed "s/^.*$tag //" || true
  grep -qF "$tag CONTROLLERS ok" "$dir/log.txt" || why="$why; no CONTROLLERS ok"
  grep -qF "$tag CTRL port 1 VIRTUAL controller profile=generic-16-8" "$dir/log.txt" || why="$why; VIRTUAL is no controller"
  grep -qF "$tag KIT ready installed=16 " "$dir/log.txt" || why="$why; the kit did not load"
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
  echo "--- audio"
  if [ -f "$dir/main.wav" ]; then
    python3 "$here/tools/analyze-wav.py" "$dir/main.wav" --channels 0,1 --kit "$dir/kit.json" \
      --kit-dir "$dir/data/Samples/TestKit" --from-s 2.5 --seconds 5.0 --spacing-ms 250 > "$dir/wav.txt" 2>&1 \
      || why="$why; the controller's pad hits did not play the kit"
    cat "$dir/wav.txt"
  else
    why="$why; no WAV"
  fi
  echo "--- screenshot: $dir/panel.png"
  png_check "$dir/panel.png" || why="$why; screenshot blank or unreadable"
  echo "--- verify"
  python3 - "$dir/log.txt" "$dir/midi-out.txt" "$tag" "$dir/main.wav" > "$dir/verify.txt" 2>&1 <<'PY' || why="$why; ctrl checks failed"
import re, struct, sys, wave
log, out, tag, wav = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
lines = [l.split(tag + " ", 1)[1].strip() for l in open(log, errors="replace") if tag + " " in l]
ok = True
def check(cond, text):
    global ok
    print(("  OK    " if cond else "  FAIL  ") + text)
    ok = ok and cond
stats = [l for l in lines if l.startswith("CTRL stats port=VIRTUAL")]
check(bool(stats), "a CTRL stats line for VIRTUAL")
if stats:
    kv = dict(re.findall(r"(\w+)=([-\w.]+)", stats[-1]))
    num = lambda k: float(kv.get(k, "nan"))
    check(num("consumed") >= 35, f"consumed {kv.get('consumed')} (>= 35: 32 pad notes, CC 70 x3, CC 116 x2)")
    check(num("triggers") == 16, f"triggers {kv.get('triggers')} (16 pad hits straight to the engine, UI-118)")
    check(num("lamps") > 0, f"lamp messages sent {kv.get('lamps')} (> 0)")
    check(num("dropped") == 0, f"dropped {kv.get('dropped')} (0)")
midi = [l for l in lines if l.startswith("MIDI stats ")]
if midi:
    kv = dict(re.findall(r"(\w+)=([-\d.]+)", midi[-1]))
    check(float(kv.get("in", "0")) >= 39, f"MIDI messages in {kv.get('in')} (>= 39: every message counted)")
for l in lines:
    if l.startswith(("AUDIO alsa_periods", "LOAD ")):
        m = re.search(r"xruns=(\d+)", l)
        if m:
            check(m.group(1) == "0", "xruns 0: " + l[:60])
try:
    recs = [l.split() for l in open(out)]
except OSError as e:
    recs = []
    check(False, f"recorded output: {e}")
pads = [r for r in recs if len(r) == 4 and r[1] == "99" and 0x24 <= int(r[2], 16) <= 0x33]
lit = [r for r in pads if int(r[3], 16) != 0]
check(len(pads) >= 16 and len(lit) >= 1,
      f"pad lamps echoed: {len(pads)} note-ons on notes 36-51 ch 10, {len(lit)} lit (>= 16, >= 1)")
check(any(l.startswith("CTRL ") and "VIRTUAL" in l for l in lines), "CTRL lines logged")
def peak_db(t0, t1):
    try:
        w = wave.open(wav)
    except Exception as e:
        return None
    rate, ch, width = w.getframerate(), w.getnchannels(), w.getsampwidth()
    w.setpos(int(t0 * rate))
    raw = w.readframes(int((t1 - t0) * rate))
    if width != 2 or not raw:
        return None
    vals = struct.unpack("<%dh" % (len(raw) // 2), raw)
    peak = max(abs(v) for i, v in enumerate(vals) if i % ch < 2) / 32768.0
    import math
    return 20 * math.log10(peak) if peak > 0 else -200.0
thru = peak_db(7.55, 7.85)
check(thru is not None and thru > -20, f"note 60 ch 1 (unbound) played through the MIDI input at ~7.6 s: peak "
      f"{thru if thru is None else round(thru, 1)} dBFS (> -20: not consumed, UI-136)")
tapped = peak_db(9.4, 10.0)
check(tapped is not None and tapped > -20, f"the virtual panel's pad 1 tap at ~9.5 s played: peak "
      f"{tapped if tapped is None else round(tapped, 1)} dBFS (> -20)")
sys.exit(0 if ok else 1)
PY
  cat "$dir/verify.txt"
}
