# Sourced by scripts/host-smoke.sh (not run on its own): defines startprefs_check <dir>, which runs its session in
# <dir>, prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch,
# $here, $tag, $p, $r (renderer), $code (launch's exit code).
#
# CHECK=startprefs (in CHECK=all too) is the check that stored UTILITY preferences are applied, not only
# stored: the data directory starts with a preferences.json (schema 1) that sets BUFFER SIZE 128, PAD THRESHOLD 9,
# PAD MODE SELECT RESPONSE OVER 1sec, AUTOSAVE 5 min and UI SCALE 125 %. One run of 2 s. Checks: "PREFS start-up
# buffer=128" and the file audio device opened with a 128-frame period (before the audio device starts); "PADS …
# threshold=9 … mode_select=OVER 1sec" (the panel decoder's and the pad controller's values); UI SCALE 125 % is the
# window scale 1 ("scale=1", the window stays 800 x 480); STOP and exit code 0.
# Artefacts: log.txt, run.txt, data/preferences.json.
startprefs_check() {
  dir=$1
  cat > "$dir/data/preferences.json" <<'EOF'
{"format": "smoke-preferences", "version": 1,
 "values": {"audio.bufferSize": 1, "pads.threshold": 9, "pads.modeSelectResponse": 1, "settings.autosave": 2,
            "ui.scale": 125}}
EOF
  cat > "$dir/run.txt" <<EOF
# generated by scripts/smoke/99-startprefs.sh (time 0 = the app's first frame)
2000 quit
EOF
  launch "$dir" "$dir/run.txt" "$dir/log.txt"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (PREFS start-up|AUDIO ok|PADS|RUN|STOP)( |$)" | sed "s/^.*$tag //" || true
  grep -F "$tag PREFS start-up" "$dir/log.txt" | grep -q " buffer=128" || why="$why; no PREFS start-up buffer=128"
  grep -F "$tag AUDIO ok" "$dir/log.txt" | grep -q "period 128 " || why="$why; audio device not opened with period 128"
  grep -qF "threshold=9 sensitivity=5 mode_select=OVER 1sec" "$dir/log.txt" || why="$why; pad preferences not applied"
  grep -F "$tag PREFS start-up" "$dir/log.txt" | grep -q " scale=1 " || why="$why; UI SCALE 125 % is not window scale 1"
  grep -qF "$tag RUN backend=$r " "$dir/log.txt" && ! grep -F "$tag RUN backend=$r " "$dir/log.txt" | grep -q "800x480" \
    && why="$why; the window is not 800 x 480"
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
}
