# Sourced by scripts/host-smoke.sh (not run on its own): defines ext_check <dir>, which runs its session in <dir>,
# prints its lines and appends failures to $why. Helpers and variables come from host-smoke.sh: launch, $here, $tag,
# $p, $exe, $r (renderer), $code (launch's exit code).
#
# CHECK=ext (in CHECK=all too) is the extensions check (the P3 extensions with their flags ON — the flag-off
# parity is every other check and the whole unit/golden/snapshot suite):
#   session  the generated test kit (tools/gen-test-kit.py) on tracks 1-16; ext.enabled + ext.trk.toggle +
#            ext.midi.learn + ext.interop.export on (environment, services/ext/ExtFlags.h); the scripted virtual MIDI
#            port (midi_providers=virtual). Script: TOGGLE on track 1 (`cmd ext-toggle 1 on`) with LOOP posted on
#            (`cmd param playback.loop 0 1`), learn track 1 PAN (`cmd ext-learn track.pan 1`); pad 1 press/release at
#            2.5 s (latches), press/release at 4.5 s (stops); the virtual port sends CC 85 = 10 at 3.0 s (captured)
#            and CC 85 = 127 at 3.6 s (applied); then export A (`cmd ext-export`, name Smoke), import A
#            (`cmd import-sp16`), export B, import B, export C; quit at 10.5 s
#   checks   MAIN (WAV ch 0/1): sound through 2.9-4.3 s (the 100 ms one-shot keeps looping after the pad was released:
#            TOGGLE), silence 2.0-2.4 s and 5.0-5.4 s (the second hit stopped it); "EXT TOGGLE … on", "EXT LEARN bound
#            ch=1 cc=85 param=track.pan scope=0", "EXT MIDI track.pan scope=0 value=64"; three "EXPORT ok", A's report
#            drops the extension data; tools/prj-dump/prj-dump.py --roundtrip of A: identical; the imports load all 16
#            samples; B and C byte-identical (an export of an imported export is a fixed point); xruns 0; STOP; exit 0.
ext_check() {
  dir=$1
  python3 "$here/tools/gen-test-kit.py" --data-dir "$dir/data" --json "$dir/kit.json" > "$dir/gen-test-kit.txt" 2>&1 \
    || why="$why; kit generation failed"
  cat > "$dir/midi.txt" <<EOF
# generated by scripts/smoke/99-ext.sh: virtual MIDI input (ms since the port opened)
3000 B0 55 0A
3600 B0 55 7F
EOF
  prj() { echo "$dir/$1/PIONEER DJ SAMPLER/Projects/Smoke.prj"; }
  cat > "$dir/script.txt" <<EOF
# generated by scripts/smoke/99-ext.sh (time 0 = the app's first frame, ~ RUN)
1500 cmd ext-state
1600 cmd ext-toggle 1 on
1700 cmd param playback.loop 0 1
1800 cmd ext-learn track.pan 1
2500 press pad1 100
2600 release pad1
4500 press pad1 100
4600 release pad1
5500 cmd ext-export $dir/exp-a Smoke
5800 cmd import-sp16 $(prj exp-a)
7000 cmd ext-export $dir/exp-b Smoke
7300 cmd import-sp16 $(prj exp-b)
8500 cmd ext-export $dir/exp-c Smoke
9000 cmd ext-state
10500 quit
EOF
  mkdir -p "$dir/config/$PROJECT_NAME"
  echo "midi_providers=virtual" > "$dir/config/$PROJECT_NAME/$PROJECT_NAME.conf"
  launch "$dir" "$dir/script.txt" "$dir/log.txt" "${p}_DEV_KIT=Samples/TestKit" "${p}_MIDI_VIRTUAL=$dir/midi.txt" \
    "${p}_EXT_ENABLED=1" "${p}_EXT_TRK_TOGGLE=1" "${p}_EXT_MIDI_LEARN=1" "${p}_EXT_INTEROP_EXPORT=1"
  [ "$code" = 0 ] || why="$why; exit code $code"
  grep -F "$tag " "$dir/log.txt" | grep -E " (AUDIO|RUN|LOAD|FATAL|KIT|EXT|EXPORT|STOP)( |$)" | sed "s/^.*$tag //" || true
  grep -F "$tag " "$dir/log.txt" | grep -E " IMPORT done" | sed "s/^.*$tag //" || true
  grep -qF "$tag STOP" "$dir/log.txt" || why="$why; no STOP"
  echo "--- verify"
  python3 - "$dir" "$tag" "$here" > "$dir/verify.txt" 2>&1 <<'PY' || why="$why; ext checks failed"
import math, re, struct, subprocess, sys, wave
d, tag, here = sys.argv[1], sys.argv[2], sys.argv[3]
lines = [l.split(tag + " ", 1)[1].strip() for l in open(d + "/log.txt", errors="replace") if tag + " " in l]
ok = True
def check(cond, text):
    global ok
    print(("  OK    " if cond else "  FAIL  ") + text)
    ok = ok and cond
def has(prefix):
    return [l for l in lines if l.startswith(prefix)]
# MAIN from the file device (16-bit, MAIN = ch 0/1).
with wave.open(d + "/main.wav", "rb") as w:
    ch, rate, n = w.getnchannels(), w.getframerate(), w.getnframes()
    raw = w.readframes(n)
x = struct.unpack("<%dh" % (len(raw) // 2), raw)
def rms(a, b):
    s, k = 0.0, 0
    for i in range(int(a * rate), min(int(b * rate), n)):
        v = (x[i * ch] / 32768.0) ** 2 + (x[i * ch + 1] / 32768.0) ** 2
        s, k = s + v, k + 2
    return 20 * math.log10(math.sqrt(s / k)) if k and s > 0 else -999.0
before, held, after = rms(2.0, 2.4), rms(2.9, 4.3), rms(5.0, 5.4)
check(before < -70, f"silent before the first hit: {before:.1f} dBFS (< -70)")
check(held > -40, f"TOGGLE: track 1 keeps sounding after its pad was released, 2.9-4.3 s: {held:.1f} dBFS (> -40)")
check(after < -70, f"the second hit stopped it, 5.0-5.4 s: {after:.1f} dBFS (< -70)")
check(bool(has("EXT TOGGLE scene=1 track=1 on")), "EXT TOGGLE scene=1 track=1 on")
check(bool(has("EXT LEARN bound ch=1 cc=85 param=track.pan scope=0")), "learned: CC 85 on channel 1 -> track.pan")
check(bool(has("EXT MIDI track.pan scope=0 value=64")), "the learned CC 85 = 127 set track 1 PAN to +64: " +
      (has("EXT MIDI")[0] if has("EXT MIDI") else "no EXT MIDI line"))
exports = has("EXPORT ok file=")
check(len(exports) == 3, f"three exports ok ({len(exports)})")
check(any("extension data ext.trk.toggle" in l for l in has("EXPORT dropped")),
      "export A reports the TOGGLE extension data as dropped")
imports = has("IMPORT done ok")
check(len(imports) == 2 and all("samples=16 loaded=16 missing=0" in l for l in imports),
      f"both imports load the 16 exported samples: {imports}")
prj = lambda k: f"{d}/exp-{k}/PIONEER DJ SAMPLER/Projects/Smoke.prj"
try:
    out = subprocess.run([sys.executable, here + "/tools/prj-dump/prj-dump.py", prj("a"), "--roundtrip"],
                         capture_output=True, text=True, timeout=120)
    check(out.returncode == 0 and "identical" in out.stdout, "prj-dump --roundtrip of export A: " +
          (out.stdout.strip().splitlines() or ["?"])[-1])
except Exception as e:
    check(False, f"prj-dump: {e}")
try:
    b, c = open(prj("b"), "rb").read(), open(prj("c"), "rb").read()
    check(b == c, f"exports B and C byte-identical ({len(b)} / {len(c)} bytes)")
except OSError as e:
    check(False, f"exports B / C: {e}")
for l in lines:
    if l.startswith(("AUDIO alsa_periods", "LOAD ")):
        m = re.search(r"xruns=(\d+)", l)
        if m:
            check(m.group(1) == "0", "xruns 0: " + l[:60])
sys.exit(0 if ok else 1)
PY
  cat "$dir/verify.txt"
}
